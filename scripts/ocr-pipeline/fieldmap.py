#!/usr/bin/env python3
"""Имя поля для каждого рукописного значения: «1164,8» → «отметка устья, м».

Зачем. Без имени поля число некуда деть. Человеку его отдать нельзя — он получит
столбик цифр без смысла; правила `verify.py` включить нельзя — им нужно имя, а не
число (из 60 незакрытых полей стенда 24 это даты, где правила дают 87–100 % и молчат
только потому, что нечем включиться).

Как. Значение на бланке всегда стоит СПРАВА от своей печатной подписи и на одной с
ней строке: «6. Скважина начата ______». Печатный слой у нас отделён по цвету, его
читает обычный OCR, и tesseract отдаёт слова с рамками. Значит подпись к значению
достаётся геометрией, без модели и без обучения:

  строка печатного слоя → слова слева от значения → имя поля по таблице правил.

Ключевая мелочь: подписью служит не вся строка, а КУСОК МЕЖДУ предыдущим значением
и этим. Иначе «13. Диаметр коронки наружный ___ мм; внутренний ___ мм» даст обоим
числам одно имя. Поэтому у каждого значения два контекста: `tail` — слова сразу
перед ним (различает наружный/внутренний), `head` — вся строка до него (говорит,
что речь о коронке, а не о башмаке). Правило смотрит на оба.

Режим сегментации у tesseract — psm 4, а не 6. На РАЗВОРОТЕ (форма-разворот,
где слева акт, справа журнал) psm 6 считает лист одним блоком и сшивает строки
левой и правой половины в одну: «АКТ НА ЗАВЕРШЕННУЮ СКВАЖИНУ 9. Пройдено в талом
грунте от до м». После такой склейки подпись к значению определить нельзя.

  fieldmap.py <страница.jpg> ...            # показать разбор глазами
  fieldmap.py --values=out/x.values.jsonl <страница> ...   # приписать имена чтениям
"""
import csv
import io
import json
import os
import re
import subprocess
import sys
import tempfile
from collections import defaultdict

from PIL import Image

from inklayer import split
from values import extract

Image.MAX_IMAGE_PIXELS = None
ONE_THREAD = dict(os.environ, OMP_NUM_THREADS="1", OMP_THREAD_LIMIT="1")


def norm(s):
    """№ бережём как слово `n`: без него «12. Скважина добита» неотличима от
    заголовка «СКВАЖИНА № ___», и пятно чернил под «добита» получает имя
    «скважина №». Обычная зачистка небуквенных знаков этот знак съедала."""
    s = s.lower().replace("ё", "е").replace("№", " n ")
    return re.sub(r"[^а-яa-z0-9]+", " ", s).strip()


# ── таблица правил ──────────────────────────────────────────────────────────────
# Порядок значим: первое подошедшее правило выигрывает, поэтому частное стоит
# раньше общего («от линии №» раньше «линия №»).
# Имена полей — РОВНО те, что в эталоне и в SPECS verify.py. Новых не выдумываем:
# имя, которого нет в SPECS, не включает ни одного правила и только делает вид,
# что поле разобрано.
RULES = [
    # (что стоит вплотную перед значением, что должно быть в строке, имя поля)
    (r"от\s*линии\s*n$",                     None,                    "от линии №"),
    (r"той\s*же\s*линии\s*n$",               None,                    "скважины той же линии №"),
    (r"от\s*скважины\s*n$",                  None,                    "от скважины №"),
    # Акт опознаём ПО СВОЕМУ ХВОСТУ («…о том, что скважина №»), а не по тому, что
    # где-то на строке нашлось слово «акт». На развороте psm 4 иногда сшивает
    # строку левой половины (акт) со строкой правой (журнал), и признак на уровне
    # строки начинал приписывать «акт:» полям соседней колонки — четыре чужих
    # имени из восемнадцати были именно отсюда.
    (r"что\s*(с)?кв\w*\s*n$",                None,                    "акт: скважина №"),
    (r"на\s*глубине$",                       r"настоящий\s*акт",      "акт: на глубине, м"),
    (r"линия\s*n$",                          None,                    "линия №"),
    (r"скважина\s*n$",                       None,                    "скважина №"),
    # то же поле, когда OCR потерял №: пускаем, но только если строка не про
    # «скважина добита / пройдена / пробурена» — там значения нет, там подчёркивают
    (r"скважина$",   r"!добита|пройдена|пробурена|остановлена|закрыта", "скважина №"),
    # перенос строки: «... от линии № [8] вверх [400] м» — на новой строке перед
    # значением остаётся один знак «№», а подпись «от линии» висит на прошлой
    (r"^n$",                                 r"^от\s*линии\s*n$",     "от линии №"),
    (r"от\s*устья$",                         None,                    "от устья, м"),
    (r"\bвниз$",                             None,                    "вниз, м"),
    (r"\bвверх$",                            None,                    "вверх, м"),
    (r"\bвлево$",                            None,                    "влево, м"),
    (r"\bвправо$",                           None,                    "вправо, м"),
    (r"азимут\s*буровой\s*линии$",           None,                    "азимут буровой линии"),
    (r"азимут\s*линии$",                     None,                    "азимут линии"),
    (r"начата$",                             None,                    "начата"),
    (r"окончена$",                           None,                    "окончена"),
    (r"закончена$",                          None,                    "закончена"),
    (r"отметка\s*устья\s*скважины,?\s*м?$",  None,                    "отметка устья, м"),
    # «Координаты: Х ____ У ____»: буква Х часто слипается с линовкой и до слов
    # не доживает, поэтому первое значение после слова «координаты» — это X
    (r"координаты?:?(\s*[хx])?$",            None,                    "координата X"),
    (r"\b[хx]$",                             r"координат",            "координата X"),
    (r"\b[уy]$",                             r"координат",            "координата Y"),
    (r"\bот$",                               r"в\s*мерзлоте",         "мерзлота от, м"),
    (r"\bдо$",                               r"в\s*мерзлоте",         "мерзлота до, м"),
    (r"общая\s*глубина\s*скважины$",         None,                    "общая глубина, м"),
    (r"глубина\s*скважины$",                 None,                    "глубина скважины, м"),
    (r"пройдено\s*по\s*ним$",                None,                    "пройдено по коренным, м"),
    (r"наружный$",                           r"коронки",              "коронка наружный, мм"),
    (r"внутренний$",                         r"коронки",              "коронка внутренний, мм"),
    (r"наружный$",                           r"башмака",              "диаметр башмака наружный, мм"),
    (r"внутренний$",                         r"башмака",              "диаметр башмака внутренний, мм"),
    (r"обсадной\s*трубы$",                   None,                    "обсадная труба, мм"),
    (r"начальный$",                          r"диаметры?\s*скважины", "диаметр скважины начальный, мм"),
    # «…диаметр керна (по пласту) ___ мм; выход керна (по пласту) ___ %» —
    # обе подписи на одной строке. Жадное `.*` в правиле диаметра накрывало и
    # хвост выхода: все четыре «100 %» уезжали в диаметр керна.
    (r"выход\s*керна(\s*по\s*пласту)?$",     None,                    "выход керна, %"),
    (r"диаметр\s*керна(\s*по\s*пласту)?$",   None,                    "диаметр керна, мм"),
    (r"на\s*расстоянии$",                    None,                    "на расстоянии, м"),
    (r"пойме\s*на$",                         None,                    "терраса"),
]
# Хвост печатной строки бывает замусорен обломками линовки («ЕН», «ыы»), поэтому
# правилу разрешён небольшой мусор после подписи, но не новое слово-подпись.
JUNK = r"(?:\s+[а-я]{1,3})?\s*$"


def match(tail, head):
    """Условие на строку с ведущим «!» — запрещающее, а не требующее."""
    for pat, need_head, field in RULES:
        if need_head:
            neg = need_head.startswith("!")
            if bool(re.search(need_head.lstrip("!"), head)) == neg:
                continue
        if re.search(pat.rstrip("$") + JUNK, tail):
            return field
    return None


# ── геометрия: строки печатного слоя ────────────────────────────────────────────
def printed_lines(printed):
    """→ [{y0,y1,words:[(x0,x1,текст)]}] по печатному слою, psm 4."""
    with tempfile.TemporaryDirectory() as tmp:
        p = os.path.join(tmp, "pr.png")
        printed.save(p)
        r = subprocess.run(["tesseract", p, "-", "-l", "rus", "--psm", "4", "tsv"],
                           capture_output=True, text=True, timeout=600, env=ONE_THREAD)
    groups = defaultdict(list)
    for w in csv.DictReader(io.StringIO(r.stdout), delimiter="\t", quoting=csv.QUOTE_NONE):
        if not w.get("text", "").strip() or float(w["conf"]) < 0:
            continue
        groups[(int(w["block_num"]), int(w["par_num"]), int(w["line_num"]))].append(
            (int(w["left"]), int(w["left"]) + int(w["width"]),
             int(w["top"]), int(w["top"]) + int(w["height"]), w["text"]))
    lines = []
    for ws in groups.values():
        ws.sort()
        lines.append(dict(y0=min(w[2] for w in ws), y1=max(w[3] for w in ws),
                          words=[(w[0], w[1], w[4]) for w in ws]))
    lines.sort(key=lambda ln: ln["y0"])
    return lines


# ПРОВЕРЕНО И ОТКЛОНЕНО 10.08. Почти все оставшиеся чужие имена — «акт: скважина №»
# вместо «скважина №», и напрашивалось объяснение: на РАЗВОРОТЕ psm 4 сшивает
# строку левой половины (акт) со строкой правой (журнал). Написал разрез строки по
# широкому печатному промежутку, в котором НЕТ рукописи (широкий промежуток С
# рукописью — это место для заполнения, его резать нельзя). Замер: 72,5 → 69,7 %
# верных имён, и ни один порог (0,055 · 0,10 · 0,16) в плюс не вышел. Значит
# склейка колонок — не главная причина, и код убран. Причину искать заново.


def _overlap(a0, a1, b0, b1):
    return max(0, min(a1, b1) - max(a0, b0))


def attach(path, vals=None):
    """→ [{box, field, tail, head}] для каждого значения страницы."""
    hand, printed, _meta = split(path)
    if vals is None:
        vals, _ = extract(path)
        vals = [dict(box=v["box"], px=v["px"]) for v in vals]
    lines = printed_lines(printed)

    # каждое значение — к своей печатной строке: та, с которой оно больше всего
    # перекрывается по вертикали И у которой есть слова слева
    per_line = defaultdict(list)
    loose = []
    for v in vals:
        x0, y0, x1, y1 = v["box"]
        best, best_ov = None, 0
        for i, ln in enumerate(lines):
            ov = _overlap(y0, y1, ln["y0"], ln["y1"])
            if ov > best_ov and any(w[1] <= x0 + 8 for w in ln["words"]):
                best, best_ov = i, ov
        if best is None or best_ov < 0.25 * (y1 - y0):
            loose.append(v)
        else:
            per_line[best].append(v)

    out = []
    for i, vs in per_line.items():
        words = lines[i]["words"]
        vs.sort(key=lambda v: v["box"][0])
        prev_x = -1
        for v in vs:
            x0 = v["box"][0]
            tail = norm(" ".join(w[2] for w in words if prev_x < w[1] <= x0 + 8))
            head = norm(" ".join(w[2] for w in words if w[1] <= x0 + 8))
            # Строку-подпись бланк переносит: «14. Диаметры башмака: наружный ___
            # мм;» и на следующей строке «внутренний ___ мм;». Своего слова
            # «башмака» у второй строки нет, поэтому к голове всегда подклеиваем
            # предыдущую строку — иначе девять внутренних диаметров из десяти
            # остаются без имени.
            if i > 0:
                head = (norm(" ".join(w[2] for w in lines[i - 1]["words"]))
                        + " " + head).strip()
            out.append(dict(box=tuple(v["box"]), field=match(tail, head),
                            tail=tail[-48:], head=head[-90:]))
            prev_x = v["box"][2]
    for v in loose:
        out.append(dict(box=tuple(v["box"]), field=None, tail="", head=""))
    out.sort(key=lambda d: (d["box"][1], d["box"][0]))
    return out


def main():
    vpath, pages = None, []
    for a in sys.argv[1:]:
        if a.startswith("--values="):
            vpath = a.split("=", 1)[1]
        else:
            pages.append(a)

    byp = defaultdict(list)
    if vpath:
        for line in open(vpath):
            if line.strip():
                o = json.loads(line)
                byp[o["page"]].append(o)

    for pg in pages:
        name = os.path.basename(pg).rsplit(".", 1)[0]
        vals = ([dict(box=o["box"], px=o.get("px", 0)) for o in byp[name]]
                if vpath else None)
        rows = attach(pg, vals)
        named = sum(1 for r in rows if r["field"])
        print(f"### {name}: значений {len(rows)}, с именем {named} "
              f"({named/max(1,len(rows)):.0%})")
        texts = {tuple(o["box"]): o["text"] for o in byp[name]} if vpath else {}
        for r in rows:
            if r["field"] or r["tail"]:
                t = texts.get(r["box"], "")
                print(f"   {str(r['field'] or '—'):32s} {t:14s} ← ...{r['tail']}")
        print()


if __name__ == "__main__":
    main()
