#!/usr/bin/env python3
"""Подчёркнутый вариант: «правого, левого (подчеркнуть)», «вправо (влево)».

Бланк печатает ДВА варианта, человек подчёркивает нужный — в двух разных
формах записи, и обе живут на реальных страницах:

  P1  «слово (альтернатива)»           — правой (левой), вправо (влево),
                                          (вниз, вверх)
  P2  «слово1, [не] слово2 (подчеркнуть)» — правого, левого (подчеркнуть);
                                          добита, не добита (подчеркнуть)

Подчёркивание — рукописный штрих, а рукопись на этом бланке уже отделена по
цвету (`inklayer.split`): штрих живёт в HAND-слое, не в печатном. Ищем его
ПОСТРОЧНЫМ сканом в узкой локальной обрезке под словом (`slots.rulings`,
применённая к hand-слою), а не связными компонентами всей страницы: у
«вправо» на `h034_13` подчёркивание СЛИВАЕТСЯ по 8-связности с рукописным
значением поля чуть ниже — единый компонент высотой 78 px вместо честных
25 у самого штриха, и порог по высоте либо режет штрих, либо пропускает
слияние, обоих сразу не бывает. rulings() не выходит за границы переданного
кропа, так что связность остальной страницы вообще не участвует.

Проверено глазами на живых примерах бланка `h034_13` (P1):

  «Расстояние на ПРАВОЙ (левой) стороне»   штрих h=13 w=86 под «правой»,
                                            под «(левой)» пусто
  «... ВПРАВО (влево) ...»                 h=25 w=110 под «вправо»,
                                            под «(влево)» пусто
  «от линии № (ВНИЗ, вверх) м»             h=12 w=67 под «(вниз,»,
                                            под «вверх)» пусто
  «на завершенную (добитую) скважину»      НИ под одним — это заголовок
                                            акта, не поле для заполнения,
                                            и отсутствие штриха здесь верно

Третий пример заодно ЧИНИТ реальную ошибку из задачи 1: поле на странице
`h034_13` там угадали как «вверх, м» по печатному тексту, а подчёркнуто
«вниз» — верное имя поля даёт эта проверка, не текст подписи целиком.

P2 найден по всему корпусу (`img300/*.jpg`, 69 страниц) — разные бланки
формулируют один смысл разными словами: «правой, левой (подчеркнуть)» и
«правого, левого (подчеркнуть)» (падеж зависит от шаблона), «добита, не
добита (подчеркнуть)», «пройдена, остановлена (подчеркнуть)». Сопоставляем
темы по ОСНОВЕ слова (`прав-`, `лев-`, `добит-`, `недобит-`), не по точной
форме — падежи и склонения бланк меняет, тема нет.

  underline.py <страница.jpg> ...     # показать разбор глазами
"""
import re
import sys

from fieldmap import printed_lines
from inklayer import split
from slots import rulings

# Темы известных пар — только то, что видено живьём в корпусе (см. докстринг),
# не выдумано по аналогии. Сопоставление по ОСНОВЕ (startswith), потому что
# бланк меняет падеж: «правой»/«правого», «добита»/«недобита».
KNOWN_TOPICS = [
    (("прав", "лев"), "берег"),
    (("вправо", "влево"), "направление от скважины"),
    (("вниз", "вверх"), "направление по линии"),
    (("недобит", "добит"), "скважина: статус"),
    (("остановлена", "пройдена"), "скважина: статус"),
]


def _norm(s):
    return re.sub(r"[^а-яa-z]+", "", s.lower())


def _topic(na, nb):
    for (pa, pb), field in KNOWN_TOPICS:
        if na.startswith(pa) and nb.startswith(pb):
            return field
        if na.startswith(pb) and nb.startswith(pa):
            return field
    return None


def has_underline(hand_im, x0, y0, x1, y1, above=20, below=18, pad=8,
                  min_frac=0.45):
    """Есть ли под словом (x0,y0,x1,y1) длинная тонкая горизонтальная полоса
    чернил у его базовой линии — подчёркивание. См. докстринг модуля про то,
    почему построчный скан в локальном кропе, а не связные компоненты страницы."""
    W, H = hand_im.size
    xa, xb = max(0, x0 - pad), min(W, x1 + pad)
    ya, yb = max(0, y1 - above), min(H, y1 + below)
    if xb <= xa or yb <= ya:
        return False
    crop = hand_im.crop((xa, ya, xb, yb))
    return bool(rulings(crop, min_frac=min_frac, max_h=8, merge_gap=10))


def _candidates_p1(words):
    """«слово (альтернатива)» — альтернатива стоит СРАЗУ следующим словом,
    либо оба слова целиком внутри скобок («(вниз, вверх)» — токенизация рвёт
    их на «(вниз,» и «вверх)», без слова-«умолчания» снаружи)."""
    for i in range(len(words) - 1):
        x0a, x1a, ta = words[i]
        x0b, x1b, tb = words[i + 1]
        opens_a = ta.startswith("(") or ta.startswith("{")
        opens_b = tb.startswith("(") or tb.startswith("{")
        closes_a = ta.rstrip(".").endswith(")") or ta.rstrip(".").endswith("}")
        if (opens_b and not opens_a) or (opens_a and not closes_a):
            yield (ta, x0a, x1a), (tb, x0b, x1b)


def _candidates_p2(words):
    """«слово1, [не] слово2 (подчеркнуть)» — маркер может стоять не сразу
    следующим словом за словом2, но идёт следом за запятой-словом через
    один-два токена (частица «не»)."""
    for j, (x0, x1, t) in enumerate(words):
        if "подчеркн" not in _norm(t):
            continue
        k = j - 1
        b = []
        while k >= 0:
            tx = words[k]
            b.insert(0, tx)
            if "," in tx[2]:
                break
            k -= 1
            if j - k > 4:      # не искать через полстроки — не тот маркер
                k = -1
                break
        if k < 0 or not b:
            continue
        a_word = b[0]
        b_words = b[1:]
        if not b_words:
            continue
        a_text = a_word[2].rstrip(",.;: ")
        b_text = " ".join(w[2] for w in b_words)
        yield (a_text, a_word[0], a_word[1]), \
              (b_text, b_words[0][0], b_words[-1][1])


def find_choices(path):
    """→ [{field, a, b, chosen, line_y}] — пары «вариант/альтернатива» на
    странице и какая подчёркнута (chosen=None, если штрих не нашёлся ни под
    одним из двух — не гадаем, а НЕОДНОЗНАЧНО, если нашёлся под обоими).

    Страницы без синего (`meta["colour"]` = False, заполнены чёрным/карандашом)
    пропускаем целиком: `inklayer.split` тогда честно отдаёт один и тот же
    слой в hand и printed, подчёркивание неотличимо от буквы самого бланка —
    сигнал в принципе не отделим, а не «плохо измерен». Проверено: без этой
    отсечки 11 «неоднозначно» из 11 приходятся ровно на такие страницы (h003,
    h006 — заполнены не синим), детектор ловит форму скобки/запятой в
    печатном тексте под обоими словами разом."""
    hand, printed, _meta = split(path)
    if not _meta["colour"]:
        return []
    lines = printed_lines(printed)

    out = []
    seen = set()
    for ln in lines:
        for (ta, x0a, x1a), (tb, x0b, x1b) in list(_candidates_p1(ln["words"])) \
                                             + list(_candidates_p2(ln["words"])):
            na, nb = _norm(ta), _norm(tb)
            field = _topic(na, nb)
            if not field:
                continue
            key = (ln["y0"], na, nb)
            if key in seen:
                continue
            seen.add(key)
            under = []
            if has_underline(hand, x0a, ln["y1"], x1a, ln["y1"]):
                under.append(ta)
            if has_underline(hand, x0b, ln["y1"], x1b, ln["y1"]):
                under.append(tb)
            out.append(dict(field=field, a=ta, b=tb,
                            chosen=under[0] if len(under) == 1 else None,
                            ambiguous=len(under) > 1,
                            line_y=ln["y0"]))
    return out


def main():
    for p in sys.argv[1:]:
        print(f"### {p}")
        for c in find_choices(p):
            status = c["chosen"] or ("НЕОДНОЗНАЧНО" if c["ambiguous"] else "не подчёркнуто")
            print(f"   {c['field']:26s} {c['a']!r:16s} / {c['b']!r:16s} → {status}")


if __name__ == "__main__":
    main()
