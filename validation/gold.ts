import type { EntityType, Vertical } from "../src/deid/entities";
import type { GoldDocument, GoldSpan } from "../src/validation";

type V = Exclude<Vertical, "common">;
type Mark = [EntityType, string];

function doc(vertical: V, id: string, text: string, marks: Mark[], quasi: string[]): GoldDocument {
  const spans: GoldSpan[] = [];
  let cursor = 0;
  for (const [type, raw] of marks) {
    const start = text.indexOf(raw, cursor);
    if (start < 0) throw new Error(`${id}: gold raw not found: ${raw}`);
    spans.push({ type, start, end: start + raw.length });
    cursor = start + raw.length;
  }
  return { id, vertical, text, spans, quasi };
}

