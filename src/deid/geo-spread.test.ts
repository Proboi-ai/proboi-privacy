import { describe, expect, it } from "bun:test";
import { detectEntities } from "./detect";
import { spreadGeoNames } from "./geo-spread";

const spread = (t: string) => spreadGeoNames(t, detectEntities(t, ["GEO_NAME"])).map((e) => e.raw);

describe("протяжка гео-имени по документу (замер ЕИС 05.08)", () => {
  it("подтверждённое имя закрывается там, где ключа уже нет", () => {
    const t = "Новотроицкое месторождение разведано в 2019 году. Запасы Новотроицка учтены балансом.";
    expect(spread(t)).toContain("Новотроицка");
  });

  it("имя в кавычках тянется так же", () => {
    const t = 'участок недр «Новорудный» лицензирован. Новорудный отработан на 60%.';
    expect(spread(t)).toContain("Новорудный");
  });

  it("омоним гасится строчными в этом же документе", () => {
    const t = "Проектная площадь застройки. Проектной документацией предусмотрено, что проектная схема учтена.";
    expect(spread(t)).toEqual([]);
  });

  it("гидроним не тянем — река названа по городу", () => {
    const t = "мост через р. Москва построен. Москва согласовала проект, Москвы это касается.";
    expect(spread(t)).toEqual([]);
  });

  it("короткая основа не тянется", () => {
    expect(spread("месторождение Оле разведано. Оле учтено.")).toEqual([]);
  });
});

describe("протяжка не запускается от многозначного ключа (судебный корпус 05.08)", () => {
  const spread2 = (t: string) => spreadGeoNames(t, detectEntities(t, ["GEO_NAME"])).map((e) => e.raw);

  it("«Новая площадь» не делает столицу гео-именем", () => {
    expect(spread2("г. Москва Новая площадь, д.8. Москвы касается решение, в Москве суд.")).toEqual([]);
  });

  it("название на площадке — не объект недр", () => {
    expect(spread2('на площадке «Меркурий» работы. Меркурий передал данные, Меркурию направлено.')).toEqual([]);
  });

  it("однозначный ключ затравку даёт", () => {
    expect(spread2("разведка месторождения Ихала. Ихалы касается лицензия.")).toContain("Ихалы");
  });
});

/**
 * Перечисление при одном ключе. Замер полноты 05.08: правило закрывало из списка ровно одно
 * имя — то, что стоит вплотную к ключу, — а остальные равноправные объекты оставались открытыми.
 */
describe("перечисление имён при одном ключе (замер 05.08)", () => {
  // Протяжка возвращает и повтор уже найденного (в проде их склеивает resolveOverlaps),
  // поэтому для теста список уникализируем — интересен состав имён, а не число спанов.
  const all = (t: string) => {
    const ents = detectEntities(t, ["GEO_NAME"]);
    return [...new Set([...ents, ...spreadGeoNames(t, ents)].map((e) => e.raw))];
  };

  it("ключ слева — список идёт направо через запятую", () => {
    const got = all("изучение строения рудных полей Сюрприз, Юбилейное, Зенит-Виктория, Петербургское с оценкой");
    for (const name of ["Сюрприз", "Юбилейное", "Зенит-Виктория", "Петербургское"]) expect(got).toContain(name);
  });

  it("ключ справа — список идёт налево через «и»", () => {
    expect(all("работы в пределах Экодинского и Чунского участков")).toContain("Экодинского");
  });

  it("уточнение в скобках цепочку не рвёт", () => {
    expect(all("по гайотам Говорова (кластер 08-3) и Вулканолог (кластер 09-1)")).toContain("Вулканолог");
  });

  it("строчное слово цепочку заканчивает", () => {
    expect(all("участок Северный, расположенный на территории Тындинского района")).toEqual(["Северный"]);
  });

  it("класс объекта именем не считается", () => {
    expect(all("месторождение Ихала, Республика Карелия, Иркутская область")).toEqual(["Ихала"]);
  });

  it("город слева от ключа не подхватывается: налево ходим только через «и»", () => {
    expect(all("115054, г. Москва, Павелецкая площадь, д. 2")).not.toContain("Москва");
  });

  it("проспект после реки — не объект недр", () => {
    expect(all("наб. реки Фонтанки (четная сторона) и Английского пр., и сообщает")).not.toContain("Английского");
  });
});
