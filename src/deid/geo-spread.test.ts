import { describe, expect, it } from "bun:test";
import { detectEntities } from "./detect";
import { spreadGeoNames } from "./geo-spread";

const spread = (t: string) => spreadGeoNames(t, detectEntities(t, ["GEO_NAME"])).map((e) => e.raw);

describe("протяжка гео-имени по документу (замер ЕИС 05.08)", () => {
  it("подтверждённое имя закрывается там, где ключа уже нет", () => {
    const t = "Новотроицкое месторождение разведано в 2019 году. Запасы Новотроицка учтены балансом.";
    expect(spread(t)).toContain("Новотроицка");
  });

  it("имя в кавычках тянется так же", () => {
    const t = 'участок недр «Новорудный» лицензирован. Новорудный отработан на 60%.';
    expect(spread(t)).toContain("Новорудный");
  });

  it("омоним гасится строчными в этом же документе", () => {
    const t = "Проектная площадь застройки. Проектной документацией предусмотрено, что проектная схема учтена.";
    expect(spread(t)).toEqual([]);
  });

  it("гидроним не тянем — река названа по городу", () => {
    const t = "мост через р. Москва построен. Москва согласовала проект, Москвы это касается.";
    expect(spread(t)).toEqual([]);
  });

  it("короткая основа не тянется", () => {
    expect(spread("месторождение Оле разведано. Оле учтено.")).toEqual([]);
  });
});

describe("протяжка не запускается от многозначного ключа (судебный корпус 05.08)", () => {
  const spread2 = (t: string) => spreadGeoNames(t, detectEntities(t, ["GEO_NAME"])).map((e) => e.raw);

  it("«Новая площадь» не делает столицу гео-именем", () => {
    expect(spread2("г. Москва Новая площадь, д.8. Москвы касается решение, в Москве суд.")).toEqual([]);
  });

  it("название на площадке — не объект недр", () => {
    expect(spread2('на площадке «Меркурий» работы. Меркурий передал данные, Меркурию направлено.')).toEqual([]);
  });

  it("однозначный ключ затравку даёт", () => {
    expect(spread2("разведка месторождения Ихала. Ихалы касается лицензия.")).toContain("Ихалы");
  });
});
