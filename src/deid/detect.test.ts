// Первый замер НЕ-ИМЕННЫХ типов ПДн (03.08, 4549 договоров ЕИС). До него мерились только
// PER/ORG/DATE/CASE, и по телефону, счёту, СНИЛС и ИНН не было ни одной цифры. Замер нашёл
// четыре дефекта подряд: код города только трёхзначный, счёт только полным названием,
// СНИЛС только аббревиатурой, ИНН только через двоеточие.
describe("privacy/deid/detect: не-именные ПДн из договоров ЕИС", () => {
  const raw = (text: string, types: EntityType[]): string[] =>
    detectEntities(text, types).map((e) => e.type + ":" + e.raw.trim());

  it("код города бывает четырёх- и пятизначным, а не только трёхзначным", () => {
    // 1349 открытых номеров из 4027 на срезе — все с таким кодом.
    expect(raw("Телефон: 8 (3812) 12-34-56", ["PHONE"])).toEqual(["PHONE:8 (3812) 12-34-56"]);
    expect(raw("Тел: +7 (34147) 2-41-45", ["PHONE"])).toEqual(["PHONE:+7 (34147) 2-41-45"]);
    expect(raw("Телефон: +7 (495) 123-45-67", ["PHONE"])).toEqual(["PHONE:+7 (495) 123-45-67"]);
  });

  it("длинная цепочка цифр телефоном не становится", () => {
    // Ровно десять цифр после «+7»/«8» — этим держится точность при широком коде города.
    expect(raw("Позиция 8 4951234567890 штук", ["PHONE"])).toEqual([]);
  });

  it("ИНН отделяют от числа не только двоеточием", () => {
    expect(raw("ИНН/УНП: 500100732259, КПП: -", ["INN"])).toEqual(["INN:ИНН/УНП: 500100732259"]);
    expect(raw("ОГРН:-324050000165895ИНН-500100732259Банк", ["INN"])).toEqual([
      "INN:ИНН-500100732259",
    ]);
  });

  it("СНИЛС пишут и полным названием, и через номер свидетельства", () => {
    expect(raw("страховой номер индивидуального лицевого счета (СНИЛС): 112-233-445 95", ["SNILS"]))
      .toHaveLength(1);
    expect(raw("№ страхового свидетельства ГПС 112-233-445 95 Телефон:", ["SNILS"])).toHaveLength(1);
    // Контрольное число остаётся сторожем при широкой подсказке.
    expect(raw("СНИЛС: 112-233-445 96", ["SNILS"])).toEqual([]);
  });

  it("счёт узнаётся по сокращённым реквизитам, но только с верным ключом по БИК", () => {
    const bik = "004525987"; // ТОФК: формат «00…», который старая маска БИК отвергала
    const acc = "03224640000000000000";
    expect(raw(`БИК: ${bik} к/с ${acc}`, ["ACCOUNT"])).toEqual([`ACCOUNT:к/с ${acc}`]);
    // Определения перед словом «счёт» в ярлык не забираются — прячется номер, а не подпись.
    expect(raw(`Расчетный/казначейский счёт: ${acc} БИК: ${bik}`, ["ACCOUNT"])).toEqual([
      `ACCOUNT:счёт: ${acc}`,
    ]);
    expect(raw(`Кор. счет ${acc} БИК: ${bik}`, ["ACCOUNT"])).toEqual([`ACCOUNT:счет ${acc}`]);
    expect(raw(`К/с (единый казначейский счет): ${acc}, БИК ${bik}`, ["ACCOUNT"])).toEqual([
      `ACCOUNT:счет): ${acc}`,
    ]);
    // Посторонний двадцатизначный номер ключ по БИК не проходит.
    expect(raw(`БИК: ${bik} Идентификатор закупки 03183005776260000380001`, ["ACCOUNT"])).toEqual([]);
  });

  it("счёт второй стороны договора проверяется по ЕЁ банку, а не по первому в документе", () => {
    // У договора две стороны и два банка, у бюджетного заказчика к ним добавляется ТОФК.
    // Проверка по первому найденному БИК отвергала счета всех остальных сторон.
    const first = "044525225";
    const second = "004525987";
    const accountOfSecond = "40702810000000000006"; // ключ сходится только со вторым БИК
    const text = `Поставщик: БИК ${first}. Заказчик: БИК ${second}, р/с ${accountOfSecond}.`;
    expect(raw(text, ["ACCOUNT"])).toEqual([`ACCOUNT:р/с ${accountOfSecond}`]);
  });
});

