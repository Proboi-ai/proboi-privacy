/**
 * Замер 06.08.2026 на архиве недропользователя (90 кусков буровых журналов и отчётов,
 * 59 документов, разметка независимой моделью через шлюз AIgate).
 *
 * Главная находка — не форма записи, а РАЗМЕТКА: наш же продовый путь распознавания скана
 * отдаёт markdown, и «в системе реки **Холой**» не подходило ни под одно правило. Снято в
 * нормализации (normalize.ts), здесь — сторожа на формы, которые за этим открылись.
 */
describe("гео на буровых журналах клиента (замер 06.08)", () => {
  const geo = (t: string) => detectEntities(t, ["GEO_NAME"]).map((e) => e.raw);
  const well = (t: string) => detectEntities(t, ["WELL"]).map((e) => e.raw);
  const lic = (t: string) => detectEntities(t, ["LICENSE_SUBSOIL"]).map((e) => e.raw);

  it("markdown вокруг названия больше не прячет его от правил", () => {
    const t = "1. Долина речки, ручья **Улан-Тугал** притока речки, ручья **Индола** в системе реки **Холой**";
    expect(geo(t).join(" ")).toContain("Улан-Тугал");
    expect(geo(t).join(" ")).toContain("Холой");
  });

  it("двоеточие после ключа — шапка журнала колонкового бурения", () => {
    expect(geo("1. Долина речки, ручья: Вилой, в системе реки: Заза")).toEqual(["ручья: Вилой", "реки: Заза"]);
  });

  it("капс и сокращение без точки", () => {
    expect(geo("РОССЫПЬ РУЧ. МОЖАЙСКИЙ РАЗРЕЗЫ")).toContain("РУЧ. МОЖАЙСКИЙ");
    expect(geo("р. Бол. Бугарихта, руч Ютеннях, ИРК 02264 БР")).toContain("руч Ютеннях");
  });

  it("ключи объектов работ: рудный узел, впадина, терраса, полигон, массив", () => {
    expect(geo("в пределах Мунинского рудного узла")).toContain("Мунинского рудного узла");
    expect(geo("сосредоточен в Корсаковско-Залогской впадине")).toContain("Корсаковско-Залогской впадине");
    expect(geo("39 | р.Бодайбо, Октябрьская терраса, ИРК")).toContain("Октябрьская терраса");
    expect(geo("40 | Васильевский полигон, запасы")).toContain("Васильевский полигон");
    expect(geo("восточной части массива Панских тундр")).toContain("Панских");
  });

  it("строчное определение между именем и ключом", () => {
    expect(geo("ореолов рассеяния олова Нечинской перспективной площади")).toContain(
      "Нечинской перспективной площади",
    );
  });

  it("жанр не переносится: чужой «участок» и чужой «массив» остаются открытыми", () => {
    expect(geo("Мировой судья Удорского судебного участка Республики")).toEqual([]);
    expect(geo("вместе с «Перечнем земельных участков и расположенных")).toEqual([]);
    expect(geo("жилой массив Северный застроен")).toEqual([]);
    expect(geo("набережная Реки Великой, д. 6")).toEqual([]);
  });

  it("«объект» — ключ только рядом с геологией", () => {
    expect(geo("работ на россыпное золото в бассейне р. Ольга, объект «Рукавчинский Ключ»")).toContain(
      "объект «Рукавчинский Ключ»",
    );
    expect(geo("осуществляло строительство объекта «Жилая застройка» 12-ти этажного")).toEqual([]);
  });

  it("список номеров скважин при одном ключе", () => {
    expect(well("технические данные по скважинам 8, 12, 16, 20, 24, 28, 32")).toContain(
      "скважинам 8, 12, 16, 20, 24, 28, 32",
    );
    expect(well("Номера скважин (на плане и разрезе): 171, 224, 336, 79")).toHaveLength(1);
    expect(well("глубины скважин 120, 130, 140 м составили")).toEqual([]);
  });

  it("десятичное число не разрезается пополам", () => {
    expect(well("11. Общая глубина скважины 4,8 м.")).toEqual([]);
    expect(well("8. Отметка устья скважины 1156,4 м")).toEqual([]);
    // А перечисление через запятую разрезом не считается: одна цифра и никакой единицы.
    expect(well("станции водозабора, скважины 1,2 и резервуара")).toContain("скважины 1");
  });

  it("лицензия: дефис перед видом и запись вовсе без вида", () => {
    expect(lic("В реестре за № МУР 00552-БП/32-95")).toContain("МУР 00552-БП");
    expect(lic("Контур лицензионной площади УДЭ 02094 уч.")).toContain("УДЭ 02094");
    expect(lic("шифр объекта МОС 12345 в таблице")).toEqual([]);
  });
});
