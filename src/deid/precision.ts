/**
 * Договорная подсказка: рядом с ней заглавное слово почти наверняка человек, даже если по
 * написанию он на русскую фамилию не похож. 41% находок стоят рядом с такой подсказкой —
 * именно она спасает «Ким», «Шмидт» и подписной блок.
 */
const CUE_PHRASES = [
  "в лице", "действующ", "именуем", "м.п.", "мп.", "подпис", "фио", "ф.и.о",
  "должность", "заказчик:", "исполнитель:", "поставщик:", "подрядчик:",
  "покупатель:", "продавец:", "арендодатель:", "арендатор:", "уполномочен",
  "доверенности", "паспорт", "снилс", "инн ", "директор", "руководител",
  "главный бухгалтер", "с одной стороны", "с другой стороны", "подпись", "расшифровка",
];

/** Окно контекста вокруг находки, в котором ищется договорная подсказка. */
const CUE_WINDOW = 120;

/**
 * Отчество ВО ВСЕХ ПАДЕЖАХ. Падежные окончания здесь не украшение: голое `-вич$` ловит только
 * именительный, и на замере из-за него терялись настоящие люди в дательном («Сергеевичу»).
 */
const PATRONYMIC_SUFFIX =
  /(?:вича|вичу|виче|вичем|вной|ична|ичны|ичну|ичной|вна|вны|вне|вну|вич)$/u;

/** Фамильные суффиксы, тоже во всех падежах. Длина слова ≥4 — иначе ловится половина языка. */
const SURNAME_SUFFIX =
  /(?:ского|скому|скими|ским|ском|ская|ской|скую|скою|ские|ских|цкого|цкому|цкими|цким|цком|цкая|цкой|цкую|цкою|ский|цкий|енко|швили|дзе|ых|их|ко|ук|юк|ян|овой|овым|ову|ове|ова|евой|евым|еву|еве|ева|ёвой|ёвым|ёву|ёве|ёва|иной|иным|ину|ине|ина|ыной|ыным|ыну|ыне|ына|ов|ев|ёв|ин|ын|ая)$/u;

/** Ведущие инициалы: «И.И. Иванов» — они не слово и в разбор не идут. */
const LEADING_INITIALS = /^[А-ЯЁ]\.\s?[А-ЯЁ]?\.?\s?/u;

/** Слово — договорная номенклатура. Стоп-лист сильнее суффикса: «Заказчик» кончается на «ик». */
function isNomenclature(word: string): boolean {
  if (word.length < 3) return false;
  const lower = word.toLowerCase();
  return NOMENCLATURE_STEMS.some((stem) => lower.startsWith(stem));
}

/** Только суффикс, БЕЗ веты номенклатуры: «Заказчика» — нет, «Директоров» — да. */
function hasNameSuffix(word: string): boolean {
  const lower = word.toLowerCase();
  if (PATRONYMIC_SUFFIX.test(lower)) return true;
  return word.length >= 4 && SURNAME_SUFFIX.test(lower);
}

/** Слово похоже на русское имя собственное по суффиксу — и при этом не номенклатура. */
function looksLikeNameWord(word: string): boolean {
  if (isNomenclature(word)) return false;
  return hasNameSuffix(word);
}

/** Значимые слова находки. Инициалы срезаются, короткий мусор отбрасывается. */
function wordsOf(raw: string): string[] {
  const core = raw.replace(LEADING_INITIALS, "");
  const words = (core.match(/[А-Яа-яЁё]+/gu) ?? []).filter((w) => w.length >= 3);
  if (words.length > 0) return words;
  return (raw.match(/[А-Яа-яЁё]+/gu) ?? []).filter((w) => w.length >= 3);
}

function hasContractCue(text: string, index: number, length: number): boolean {
  const window = text
    .slice(Math.max(0, index - CUE_WINDOW), Math.min(text.length, index + length + CUE_WINDOW))
    .toLowerCase();
  return CUE_PHRASES.some((cue) => window.includes(cue));
}

/**
 * Кандидат от NER — ложное срабатывание.
 *
 * Правило одно: оставляем, если находка ПОХОЖА НА ИМЯ по написанию, либо стоит рядом с
 * договорной подсказкой. Подсказка не спасает номенклатуру: «Заказчик» в подписном блоке
 * стоит ровно там же, где человек, и без этой оговорки фильтр не снимал бы ничего.
 */
export function isFalsePositivePerson(raw: string, text: string, index: number): boolean {
  const words = wordsOf(raw);
  const looksLikeName = words.some(looksLikeNameWord);
  if (looksLikeName) return false;
  const nomenclature = words.some(isNomenclature);
  return nomenclature || !hasContractCue(text, index, raw.length);
}

/** Разрыв колонок таблицы или отступ вёрстки: внутри одного значения его не бывает. */
const LAYOUT_GAP = /[  \t]{3,}|\n/u;

/** Буквы, ради которых значение вообще имеет смысл прятать. */
const LETTER = /[А-Яа-яЁёA-Za-z]/gu;

/**
 * Обрезает у спана мусорные края и отбрасывает спан, если прятать в нём нечего.
 *
 * На договоре из ЕИС в 220 КБ, извлечённом из плохого PDF, Natasha вернула спаны из ОДНИХ
 * ПРОБЕЛОВ и обрывков вроде « ука». Они уезжали в сейф наравне с людьми: документ приходил
 * к модели с дырами на месте отступов, сейф раздувался, а счётчик остатков показывал 15 931
 * «утечку» — на самом деле просто повторы пробельных строк.
 *
 * Спан, внутри которого разрыв колонок или перенос строки, отбрасывается целиком: значение,
 * пересекающее вёрстку, — это не одна сущность, а склейка двух ячеек.
 */
function tidyNerSpan(e: DetectedEntity, text: string): DetectedEntity | null {
  const leading = e.raw.length - e.raw.trimStart().length;
  const raw = e.raw.trim();
  if (raw.length < 2) return null;
  if ((raw.match(LETTER) ?? []).length < 2) return null;
  if (LAYOUT_GAP.test(raw)) return null;
  if (leading === 0 && raw.length === e.raw.length) return e;
  const index = e.index + leading;
  // Обрезка меняет координаты, поэтому сверяемся с исходным текстом: если после обрезки
  // спан не совпадает с документом дословно, это не наша строка — безопаснее отбросить.
  return text.slice(index, index + raw.length) === raw ? { ...e, raw, index } : null;
}

/**
 * Чистит находки NER-слоя: убирает мусорные спаны у всех типов и ложных людей у PER.
 * Находки правил не трогаются вовсе — у них свои проверки и своя точность.
 */
export function filterNerPersons(text: string, ents: readonly DetectedEntity[]): DetectedEntity[] {
  const out: DetectedEntity[] = [];
  for (const e of ents) {
    if (e.source !== "ner") {
      out.push(e);
      continue;
    }
    const tidy = tidyNerSpan(e, text);
    if (tidy === null) continue;
    if (tidy.type === "PER" && isFalsePositivePerson(tidy.raw, text, tidy.index)) continue;
    out.push(tidy);
  }
  return out;
}

// ─── Решения арбитра от 31.07 ────────────────────────────────────────────────
//
// Ниже два правила, которые не выводятся из кода: это решения владельца по разметке 150
// находок (`training/expanded/VERIFIER-STAGE1-2026-07-31.md`). Оба применяются к находкам
// ЛЮБОГО слоя — и правил, и модели — и ДО протяжки: иначе мемориальное имя из названия
// больницы разъезжается по всему документу.

/**
 * Мемориальное имя в названии учреждения, улицы, награды: «больница имени Иванова»,
 * «музей им. Петровой». Формально это имя человека, но человек здесь не субъект данных:
 * он назван публично и обычно давно умер, а спрятать его — значит изувечить название
 * организации, по которому документ читается.
 *
 * РЕШЕНИЕ АРБИТРА: не скрывать (вопрос 1 разметки 31.07, 19 из 19 находок блока Б).
 * До решения этот класс был самым крупным остатком ошибок — 22 из 54 на корпусе 237
 * договоров и 12 из 42 на корпусе 85, — и моделям-судьям он не поддавался: они расходились
 * на нём в 48% случаев против 1,8% в среднем.
 *
 * «От имени» и «от своего имени» исключены намеренно: «действующий от имени Иванова И.И.» —
 * это доверенность, там человек как раз субъект данных. В корпусе таких не встретилось, но
 * цена ошибки здесь односторонняя (утечка), поэтому оговорка стоит заранее.
 */
// `\b` здесь не годится: в JS он считает границу по ASCII `\w`, и с кириллицей молча не
// срабатывает вовсе — та же грабля, из-за которой в `detect.ts` все границы написаны через
// lookaround. Проверено тестом: с `\bимени` мемориальные имена не отбрасывались.
const MEMORIAL_CUE = /(?<![А-Яа-яЁё])(?:имени|им\.)\s*["'«»]?\s*$/iu;
const NOT_MEMORIAL = /(?<![А-Яа-яЁё])(?:от|своего)\s+имени\s*$/iu;
const MEMORIAL_WINDOW = 32;

/**
 * Между подсказкой «имени» и находкой могут стоять ДРУГИЕ части того же мемориального имени:
 * «школа №2 имени Кузнецова ⟦Ивана Петровича⟧ станицы …». Детектор разрезал имя на две
 * находки, и первая ушла по подсказке, а вторая осталась — на замере 31.07 таких выживших
 * оказалось три из 60 ошибок. Поэтому подсказку ищем не только вплотную, но и через уже
 * пройденные части имени: заглавные слова, инициалы и дефисы. Ничего кроме них — иначе
 * «имени» из соседнего предложения начнёт отменять живых людей.
 */
// Одна часть имени: заглавное слово, слово капсом или инициалы. Зазор — только пробелы и
// запятые ОДНОЙ строки: перевод строки, кавычка и граница ячейки таблицы проход обрывают, иначе
// «больница имени Кузнецова ⏎ Главный врач Иванов И.И.» отменила бы живого человека.
const NAME_PART_BEFORE = /(?:[А-ЯЁ][а-яё]+|[А-ЯЁ]{2,}|[А-ЯЁ]\.(?:[  ]?[А-ЯЁ]\.)?)[  \t,]*$/u;
/**
 * Звание или почётное слово между подсказкой и именем: «имени академика Кузнецова», «имени Героя
 * России Кузнецова», «улица Космонавта Кузнецова». Пишутся строчными, поэтому проход по частям
 * имени на них обрывался — на независимой проверке 31.07 из-за этого выжили четыре мемориальных
 * имени из 22 ошибок. Список закрытый и состоит из ЗВАНИЙ, а не из фамилий, поэтому живого
 * человека он отменить не может: «академик» перед именем в договоре стоит только у мемориала.
 */
const HONORIFIC_BEFORE =
  /(?:академик[а-яё]*|акад\.|профессор[а-яё]*|проф\.|геро[йя][а-яё]*|маршал[а-яё]*|генерал[а-яё]*|ген\.|адмирал[а-яё]*|адм\.|доктор[а-яё]*|д-ра?|писател[а-яё]*|поэт[а-яё]*|композитор[а-яё]*|л[её]тчик[а-яё]*|космонавт[а-яё]*|хирург[а-яё]*|педагог[а-яё]*|у?ч[её]н[а-яё]*)[  \t]*$/iu;


function isMemorialMention(text: string, index: number): boolean {
  let cut = text.slice(Math.max(0, index - 96), index);
  // Отступаем назад максимум на три части имени: «имени Кузнецова ⟦Ивана Петровича⟧».
  for (let step = 0; step < 4; step++) {
    if (MEMORIAL_CUE.test(cut)) return !NOT_MEMORIAL.test(cut);
    const honor = HONORIFIC_BEFORE.exec(cut);
    if (honor !== null && honor.index > 0) {
      cut = cut.slice(0, honor.index);
      continue;
    }
    const m = NAME_PART_BEFORE.exec(cut);
    if (m === null || m.index === 0) return false;
    cut = cut.slice(0, m.index);
  }
  return false;
}

/**
 * Роль, прилипшая к инициалам: «Заказчика Е.В.», «Заведующий Л.Г.».
 *
 * РЕШЕНИЕ АРБИТРА: находка ошибочна — захвачено лишнее (вопрос 3 разметки 31.07). Поэтому
 * роль СРЕЗАЕТСЯ, а не отбрасывается вместе с находкой: инициалы — персональные данные, и
 * закрыть их надо, иначе отказ от находки обернулся бы утечкой.
 *
 * Суффикс сильнее стоп-листа, и это важно именно здесь: «Директоров», «Главных», «Приставко»
 * — настоящие фамилии, начинающиеся с основы из списка номенклатуры. Срезаем только слово,
 * которое на фамилию НЕ похоже ни одним суффиксом.
 */
function trimLeadingNomenclature(e: DetectedEntity, text: string): DetectedEntity | null {
  const m = /^([А-ЯЁ][А-Яа-яЁё-]*)([  \t]+)(.+)$/su.exec(e.raw);
  if (m === null) {
    // Одно слово и оно номенклатура — прятать нечего: такие находки приходят протяжкой
    // поверхности («Поставщика» после ложной личности) и людей среди них не встретилось.
    const solo = e.raw.trim();
    return isNomenclature(solo) && !hasNameSuffix(solo) ? null : e;
  }
  const [, head, gap, rest] = m as unknown as [string, string, string, string];
  if (!isNomenclature(head) || hasNameSuffix(head)) return e;
  // В остатке должно остаться что прятать: инициал или заглавное слово.
  if (!/[А-ЯЁ]\.|[А-ЯЁ][а-яё]/u.test(rest)) return null;
  const index = e.index + head.length + gap.length;
  return text.slice(index, index + rest.length) === rest ? { ...e, raw: rest, index } : e;
}

/**
 * Применяет решения арбитра к находкам ЛЮБОГО слоя. Вызывается до протяжки.
 */
/**
 * Шаблон-заготовка бланка, а не человек: в подписном блоке печатают «И.О. Фамилия», «Фамилия
 * И.О.», «(Ф.И.О.)» — это подсказка, куда вписать имя. Прятать нечего: ни одного персональных
 * данных в строке нет, а находка портит бланк. Список закрытый и из служебных слов, поэтому
 * стоп-листом здесь ничего не рискуем.
 */
/**
 * АДРЕС, а не человек. Два случая с независимой проверки 31.07:
 *   • тип улицы попал В САМУ находку: «⟦Улица Академика Арцимовича⟧»;
 *   • находка стоит между типом улицы и номером дома: «ул. Космонавта ⟦А.Г. Николаева⟧, д. 29б».
 * Оба — топоним: улица названа в честь человека, но субъекта данных в документе нет, а спрятать
 * её значит испортить адрес поставки. Правило держится на ДВУХ сторонах сразу (тип улицы слева и
 * номер дома справа), поэтому живого человека в подписном блоке оно не задевает: там ни того,
 * ни другого нет.
 */
const STREET_TYPE_IN_VALUE =
  /(?<![А-Яа-яЁё])(?:улиц[аеуы]|переул[а-яё]*|проспект[а-яё]*|бульвар[а-яё]*|шоссе|площад[а-яё]+|набережн[а-яё]+|проезд[а-яё]*|тупик[а-яё]*)(?![А-Яа-яЁё])/iu;
const STREET_TYPE_BEFORE =
  /(?<![А-Яа-яЁё])(?:ул\.|улиц[аеы]|пер\.|переул[а-яё]*|пр-?кт\.?|просп\.|проспект[а-яё]*|б-?р\.?|бульвар[а-яё]*|шоссе|пл\.|площад[а-яё]+|наб\.|набережн[а-яё]+)[  \t]*(?:[А-ЯЁ][а-яё]+[  \t]*)?$/iu;
const HOUSE_AFTER = /^[,;]?[  \t]*(?:д\.|дом|зд\.|здани|корп|стр\.|влад|\d)/iu;

function isStreetAddress(raw: string, text: string, index: number): boolean {
  if (STREET_TYPE_IN_VALUE.test(raw)) return true;
  const before = text.slice(Math.max(0, index - 48), index);
  const after = text.slice(index + raw.length, index + raw.length + 12);
  return STREET_TYPE_BEFORE.test(before) && HOUSE_AFTER.test(after);
}

/**
 * АВТОР В БИБЛИОГРАФИЧЕСКОЙ ССЫЛКЕ, а не субъект данных.
 *
 * РЕШЕНИЕ АРБИТРА (31.07, вопрос 4): «учебник по литературе не маскировать, но для этого надо
 * быть в контексте». Поэтому правило требует библиографическую обстановку РЯДОМ — «Учебник»,
 * «класс», «под ред.», издательство, ФГОС, — и молчит, если её нет. Имя автора в спецификации на
 * поставку учебников это часть НАЗВАНИЯ ТОВАРА: скрыв его, мы портим предмет закупки, а никого
 * не защищаем — автор назван на обложке тиражом в сотни тысяч.
 *
 * Две страховки. Окно узкое (80 знаков): в договоре школы подписант может стоять в той же
 * таблице, что и список учебников, и широкое окно захватило бы его. И подписная подсказка
 * вплотную отменяет правило целиком: «в лице директора Кузнецовой И.И.» рядом со словом
 * «учебники» остаётся скрытым.
 */
const BIBLIO_CUE =
  /(?:учебник[а-яё]*|хрестомати[а-яё]+|практикум[а-яё]*|атлас[а-яё]*|рабоч[а-яё]+ программ[а-яё]+|под\s+ред(?:\.|акцией)|издательств[а-яё]*|просвещени[ея]|ФГОС|ISBN|\d{1,2}\s*класс[а-яё]*|класс[а-яё]*\s*\d{1,2})/iu;
const BIBLIO_WINDOW = 120;

function isBibliographicMention(raw: string, text: string, index: number): boolean {
  if (hasSignatoryCue(text, index)) return false;
  const window = text.slice(
    Math.max(0, index - BIBLIO_WINDOW),
    Math.min(text.length, index + raw.length + BIBLIO_WINDOW),
  );
  return BIBLIO_CUE.test(window);
}

const FORM_PLACEHOLDER = /^(?:[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?)?(?:фамилия|отчество|ф\.?и\.?о\.?)(?:\s?[А-ЯЁ]\.\s?[А-ЯЁ]\.?)?$/iu;

/**
 * Подпись живого человека рядом: подсказки СИЛЬНЫЕ и ВПЛОТНУЮ, а не в окне 120 знаков. Строгость
 * тут не придирка: широкое окно всегда захватывает «в лице» из шапки договора — а там же стоит и
 * название больницы с мемориальным именем, — и документная согласованность ниже не работала бы.
 */
const SIGNATORY_CUE =
  /(?:в лице|действующ[а-яё]*|подпис[а-яё]*|расшифровка|должность|главн[а-яё]+ врач|директор[а-яё]*|руководител[а-яё]*|заведующ[а-яё]*|\/)[  \t:]*$/iu;

function hasSignatoryCue(text: string, index: number): boolean {
  return SIGNATORY_CUE.test(text.slice(Math.max(0, index - 48), index));
}

/** Ключ значения без пробелов: «Б. В. Кузнецова» и «Б.В. Кузнецова» — одно и то же имя. */
function valueKey(raw: string): string {
  return raw.replace(/[\s ]+/gu, "").toLowerCase();
}

/**
 * ДОКУМЕНТНАЯ СОГЛАСОВАННОСТЬ мемориального имени.
 *
 * Мемориальное имя стоит в документе много раз: в полном названии учреждения («имени академика
 * Кузнецова»), в сокращённом («ГКБ № 31 им. акад. Кузнецова»), в реквизитах, в шапке таблицы —
 * и подсказка «имени» есть НЕ у каждого вхождения. На независимой проверке 31.07 из-за этого
 * выживало три ошибки из пяти непойманных: то же имя, другое вхождение, подсказки рядом нет.
 *
 * Поэтому: значение, признанное мемориальным ХОТЬ РАЗ, не скрывается и в остальных местах ЭТОГО
 * документа — но только если ни у одного его вхождения нет подписной подсказки вплотную.
 * Оговорка страхует единственный опасный случай: однофамилец мемориального человека подписывает
 * тот же документ. Тогда правило отключается целиком, и прячется всё, как раньше.
 */
export function refinePersons(text: string, ents: readonly DetectedEntity[]): DetectedEntity[] {
  const memorial = new Set<string>();
  const signatory = new Set<string>();
  for (const e of ents) {
    if (e.type !== "PER") continue;
    const key = valueKey(e.raw);
    if (isMemorialMention(text, e.index)) memorial.add(key);
    if (hasSignatoryCue(text, e.index)) signatory.add(key);
  }

  const out: DetectedEntity[] = [];
  for (const e of ents) {
    if (e.type !== "PER") {
      out.push(e);
      continue;
    }
    if (FORM_PLACEHOLDER.test(e.raw.trim())) continue;
    const key = valueKey(e.raw);
    if (memorial.has(key) && !signatory.has(key)) continue;
    if (isMemorialMention(text, e.index)) continue;
    if (isStreetAddress(e.raw, text, e.index)) continue;
    if (isBibliographicMention(e.raw, text, e.index)) continue;
    const trimmed = trimLeadingNomenclature(e, text);
    if (trimmed !== null) out.push(trimmed);
  }
  return out;
}
