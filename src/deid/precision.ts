  "цедент", "цессионар", "должник", "кредитор", "правообладател", "пользовател",
  "форм", "рубл", "перевозчик", "грузоотправител", "грузополучател",
  "выгодоприобретател", "учреждени", "предприяти", "организаци", "участник",
  "победител", "правительств", "министерств", "администраци", "уполномоченн",
  "приемк", "поставк", "передач", "оплат", "цен", "срок", "качеств", "количеств",
