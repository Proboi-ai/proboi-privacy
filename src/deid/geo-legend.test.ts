import { describe, expect, it } from "bun:test";

import { detectEntities } from "./detect";
import { detectLegendNames, legendItemIsName } from "./geo-legend";

const names = (text: string): string[] =>
  detectEntities(text, ["GEO_NAME"])
    .filter((e) => e.type === "GEO_NAME")
    .map((e) => e.raw);

/** Легенда карты из архива недропользователя (doc-028), подлинный markdown распознавания. */
const MAP_LEGEND = `# Карта фактического материала

### Основные топографические названия (на карте)
*   Прав. Тюбелях
*   Потерянный
*   пос. Старый Оротук
*   Заграничный
*   г. Ляглака
*   Безводный
*   Лев. Чыбагалах
*   Даркяай
*   оз. Оротук
*   р. Колыма

---
`;

/** Геологическая легенда (doc-051): под тем же видом заголовка — породы и значки, не имена. */
const GEOLOGICAL_LEGEND = `## Условные обозначения

**Нера-бохапчинский комплекс габбро-гранит-диоритовый гипабиссальный малых интрузий**
*   γτJ3sb5: Вторая фаза диорит-порфиритов, дайки диоритов
*   γτJ3sb2: Пятая фаза: дайки гранит-порфиров

**Тектоника**
*   Разрывные нарушения

**Изолинии геохимических аномалий золота вторичных ореолов рассеяния, г/т**
*   0,005
*   Контур комплексной геохимической аномалии

**Данные предшественников**
*   **K-1701**: Канавы пройденные 2017 г. и их номера
*   Содержание золота в штуфных пробах (1957 г.)
`;

/** Легенда условных знаков (doc-028): описания значков, а не названия. */
const SYMBOL_LEGEND = `### Условные обозначения
*   Линии профиля с пунктами наблюдения, номера пунктов
*   Точка наблюдения
*   Места отбора штуфных проб
`;

describe("легенда карты — список названий под заголовком", () => {
  it("берёт все названия из секции топографических названий", () => {
    const found = names(MAP_LEGEND);
    for (const expected of [
      "Прав. Тюбелях",
      "Потерянный",
      "Заграничный",
      "Безводный",
      "Лев. Чыбагалах",
      "Даркяай",
    ]) {
      expect(found).toContain(expected);
    }
    // Родовой термин остаётся при имени — как у гидронимов в detect.ts.
    expect(found.some((n) => n.includes("Ляглака"))).toBe(true);
    expect(found.some((n) => n.includes("Оротук"))).toBe(true);
  });

  it("не трогает геологическую легенду: породы, индексы фаз и пояснения к значкам", () => {
    expect(detectLegendNames(GEOLOGICAL_LEGEND)).toEqual([]);
  });

  it("не трогает описания условных знаков", () => {
    expect(detectLegendNames(SYMBOL_LEGEND)).toEqual([]);
  });

  it("берёт зоны из подписей на карте, но не служебные шифры выработок", () => {
    const found = names(
      `**Обозначения на карте:**\n*   Зона 9\n*   Зона Медная\n` +
        `*   K3124, K3123, K3129 (обозначения участков/выработок)\n*   γ,P,μ (геологические индексы)\n`,
    );
    expect(found).toContain("Зона 9");
    expect(found).toContain("Зона Медная");
    expect(found.join(" ")).not.toContain("K3124");
    expect(found.join(" ")).not.toContain("μ");
  });

  it("секция кончается на горизонтальной черте и на обычном абзаце", () => {
    const after = detectLegendNames(
      `### Топографические названия\n*   Безводный\n\n---\n\n*   Приложение\n*   Ведомость\n`,
    );
    expect(after.map((n) => n.raw)).toEqual(["Безводный"]);
  });

  it("список без подходящего заголовка не разбирается вовсе", () => {
    expect(detectLegendNames(`### Состав работ\n*   Безводный\n*   Заграничный\n`)).toEqual([]);
  });

  it("элемент со строчным словом — это описание значка, а не название", () => {
    expect(legendItemIsName("Точка наблюдения")).toBe(false);
    expect(legendItemIsName("Разрывные нарушения")).toBe(false);
    expect(legendItemIsName("Потерянный")).toBe(true);
    expect(legendItemIsName("пос. Старый Оротук")).toBe(true);
  });
});

describe("перечисление объектов недр при одном ключе", () => {
  it("ключ во множественном числе + список имён без узнаваемой формы", () => {
    // Подлинная строка из отчёта клиента: ни одно из четырёх имён не имеет ни
    // именительного суффикса, ни топонимного — форму заменяет само перечисление.
    const found = names(
      "На участках Куртуя, Сарма, Курга, Анай мощность рифогенных доломитов более 150 м",
    );
    expect(found.join(" ")).toContain("Куртуя, Сарма, Курга, Анай");
  });

  it("повтор ключа в ячейке таблицы", () => {
    const found = names("| участок Куртун участок Сарма | - \" - | участок Курга участок Анай |");
    expect(found).toContain("участок Куртун участок Сарма");
    expect(found).toContain("участок Курга участок Анай");
  });

  it("перечисление в скобках после сильного ключа", () => {
    const found = names(
      "мелкие месторождения коренного золота на Полярном Урале (Новогоднее-Монто, Дальнее), а так же",
    );
    expect(found).toContain("Новогоднее-Монто, Дальнее");
  });

  it("не берёт чужие участки: земельные, судебные, лесные", () => {
    expect(names("на земельных участках Иванова, Петрова и Сидорова")).toEqual([]);
    expect(names("в судебных участках Ленинского, Кировского районов")).toEqual([]);
  });

  it("одно имя перечисления не образует — правило не срабатывает", () => {
    expect(names("на участках Схему размещения согласовать")).toEqual([]);
  });
});

describe("имя-метка строки таблицы месторождений", () => {
  it("берёт имена с геологическим описанием справа", () => {
    const found = names(
      "| **Наталкин, Павлик:** главнейшими структурами являются 2-образные в плане рудовмещающие зоны" +
        " <br> **Боец:** рудовмещающими являются зоны метасоматоза среднего" +
        " <br> **Родионовское:** рудоконтролирующей структурой является наличие пластины" +
        " | **Золотая, Левое:** Локализованы в брахиантиклинальных складках надзатружных зон" +
        " <br> **Школьное:** Локализовано в гранитном штоке подошвенного возраста" +
        " <br> **Кутиннах:** Локализовано в эодрокальной части дойкообразного тела" +
        " | **Ветреное:** Главными рудовмещающими структурами являются зоны дробления",
    );
    for (const expected of [
      "Наталкин, Павлик",
      "Боец",
      "Родионовское",
      "Золотая, Левое",
      "Школьное",
      "Кутиннах",
      "Ветреное",
    ]) {
      expect(found).toContain(expected);
    }
  });

  it("без геологического описания справа метка — это фамилия говорящего", () => {
    expect(names("Иванов: пояснил суду, что участия в сделке не принимал")).toEqual([]);
    expect(names("| **Составил:** Кунько Г.Т.")).toEqual([]);
  });

  it("рубрика протокола на «-ли» именем объекта не бывает", () => {
    expect(
      names("ПОСТАНОВИЛИ: Представить «Отчет о результатах работ на россыпное золото»"),
    ).toEqual([]);
  });
});

describe("добор мелких форм", () => {
  it("приток сокращением: «пр. пр. Берелех»", () => {
    const found = names("| 1 | руч. Банир, пр. пр. Берелех, Лицензия ЯКУ 02534 БР |");
    expect(found).toContain("пр. пр. Берелех");
    // Соседнее слово из перечисления в имя не уезжает.
    expect(found.join(" ")).not.toContain("Лицензия");
  });

  it("капсовый заголовок: ключ «рудный узел» справа от имени", () => {
    const found = names(
      "ОТЧЕТ О РЕЗУЛЬТАТАХ ГЕОЛОГИЧЕСКОГО ИЗУЧЕНИЯ (ПОИСКИ И ОЦЕНКА) В ПРЕДЕЛАХ " +
        "МУНГИНСКОГО РУДНОГО УЗЛА С ТЭО ВРЕМЕННЫХ РАЗВЕДОЧНЫХ КОНДИЦИЙ",
    );
    expect(found.join(" ")).toContain("МУНГИНСКОГО");
  });
});
