import { describe, it, expect } from "bun:test";
import { normalizeForDetection, softenAllCaps, toSourceSpan } from "./normalize";
import { detectEntities } from "./detect";

const norm = (s: string): string => normalizeForDetection(s).text;

describe("privacy/deid/normalize: порча из PDF, DOCX и сканов", () => {
  it("перенос по слогам склеивается обратно", () => {
    expect(norm("Отчёт составил Кова-\nлёв Д.А.")).toBe("Отчёт составил Ковалёв Д.А.");
    expect(norm("Отчёт составил Кова-\n  лёв Д.А.")).toBe("Отчёт составил Ковалёв Д.А.");
  });

  it("осмысленный дефис не трогаем", () => {
    // Составная фамилия и перенос перед ЗАГЛАВНОЙ — это не перенос слова, а список/связка.
    expect(norm("Тер-Петросян А.Б.")).toBe("Тер-Петросян А.Б.");
    expect(norm("Иванов -\nПетров")).toBe("Иванов -\nПетров");
  });

  it("разрядка схлопывается, но не съедает соседнее слово", () => {
    expect(norm("Отчёт составил К о в а л ё в  Д. А.")).toBe("Отчёт составил Ковалёв  Д. А.");
    // Цепочка обязана начинаться с начала слова, иначе «составил» + «К о в...» склеивались
    // в «составилКовалёв».
    expect(norm("Отчёт составил К о в а л ё в")).toBe("Отчёт составил Ковалёв");
  });

  it("короткие цепочки одиночных букв разрядкой не считаются", () => {
    expect(norm("работы в и з районе")).toBe("работы в и з районе");
  });

  it("латинские двойники чинятся по слову целиком", () => {
    // Ведущая «K» окружена пробелом и латинской «o» — посимвольное правило её не берёт.
    expect(norm("Отчёт составил Koвaлёв")).toBe("Отчёт составил Ковалёв");
  });

  it("честная латиница остаётся латиницей", () => {
    for (const s of ["John Smith", "coop mode", "Anna Kowalski"]) expect(norm(s)).toBe(s);
  });

  it("цифра вместо буквы чинится только внутри слова с кириллицей", () => {
    expect(norm("Задание направлено 0льге")).toBe("Задание направлено Ольге");
    // Номера и коды не трогаем: там цифра осмысленна.
    expect(norm("скважина Р-812/1 и 0")).toBe("скважина Р-812/1 и 0");
  });

  it("неразрывный пробел приводится к обычному", () => {
    expect(norm("Ковалёв Д.А.")).toBe("Ковалёв Д.А.");
  });

  it("чистый текст не меняется и отдаёт unchanged", () => {
    const n = normalizeForDetection("Отчёт составил Ковалёв Д.А.");
    expect(n.unchanged).toBe(true);
    expect(n.text).toBe("Отчёт составил Ковалёв Д.А.");
  });
});

describe("privacy/deid/normalize: координаты и капс", () => {
  it("спан возвращается в координаты ИСХОДНОГО текста", () => {
    const source = "Отчёт составил К о в а л ё в  Д. А.";
    const n = normalizeForDetection(source);
    const start = n.text.indexOf("Ковалёв");
    const [from, to] = toSourceSpan(n, start, start + "Ковалёв".length);
    expect(source.slice(from, to)).toBe("К о в а л ё в");
  });

  it("капс смягчается, аббревиатуры и орг-формы — нет", () => {
    expect(softenAllCaps("КОВАЛЁВ Д.А.")).toBe("Ковалёв Д.А.");
    expect(softenAllCaps("ООО «ГеоПроект» и ФГБУ «НИИ»")).toBe("ООО «ГеоПроект» и ФГБУ «НИИ»");
  });
});

describe("privacy/deid/normalize: детекция на порченом тексте", () => {
  // Значение в сейф и замена в документ обязаны идти из ИСХОДНОГО текста, иначе
  // де-ид подставит в документ строку, которой там не было.
  it("ФИО находится и отдаётся ровно в исходном написании", () => {
    for (const [source, expected] of [
      ["Отчёт составил Кова-\nлёв Д.А.", "Кова-\nлёв Д.А."],
      ["Отчёт составил К о в а л ё в  Д. А.", "К о в а л ё в  Д. А."],
      ["Отчёт составил Koвaлёв Д.А.", "Koвaлёв Д.А."],
      ["Отчёт составил КОВАЛЁВ Д.А.", "КОВАЛЁВ Д.А."],
      ["Отчёт составил Ковалёв Д.А.", "Ковалёв Д.А."],
    ] as const) {
      const got = detectEntities(source, ["PER"]);
      expect(got.map((e) => e.raw)).toContain(expected);
      // спан обязан указывать на то же место в исходной строке
      const hit = got.find((e) => e.raw === expected)!;
      expect(source.slice(hit.index, hit.index + hit.raw.length)).toBe(expected);
    }
  });

  it("геологические объекты в капсе людьми не становятся", () => {
    for (const text of [
      "ЮЖНО-МИХАЙЛОВСКОЕ МЕСТОРОЖДЕНИЕ разведано",
      "125993 МОСКВА, УЛ. Б. ГРУЗИНСКАЯ, 4/6",
      "ВОСТОЧНО-ОМСКИЙ УЧАСТОК передан в фонд",
    ]) {
      expect(detectEntities(text, ["PER"])).toHaveLength(0);
    }
  });
});
