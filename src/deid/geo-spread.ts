/**
 * Протяжка ГЕО-ИМЕНИ по документу.
 *
 * ЗАЧЕМ. Правило видит имя объекта только рядом с ключевым словом: «Новотроицкое
 * месторождение», «участок недр «Новорудный»». Дальше по документу автор ключ не повторяет
 * и пишет имя голым — «в пределах Новотроицка», «Новорудный отработан на 60%». Контекста
 * рядом нет, и правилу такое вхождение взять неоткуда. Замер на корпусе ЕИС (05.08,
 * 584 документа геологоразведки): 208 таких вхождений оставались открытыми — а это ровно
 * та привязка к местности, ради которой гео-тип и маскируется. У одного документа про
 * Новотроицкое месторождение открытыми стояли 96 упоминаний названия.
 *
 * ЧТО ДЕЛАЕМ. Тот же приём, что у протяжки личности (spread.ts): контекст, которого не
 * хватает, в документе УЖЕ ЕСТЬ. Берём ПОДТВЕРЖДЁННЫЕ гео-имена, снимаем падежное
 * окончание до основы и закрываем все прочие вхождения этой основы в том же документе.
 *
 * ПОЧЕМУ ЭТО НЕ РОНЯЕТ ТОЧНОСТЬ. Четыре ограничителя, каждый оплачен замером:
 *   • ЗАТРАВКА ТОЛЬКО ОТ ОДНОЗНАЧНОГО КЛЮЧА («месторождение», «недра», «залежь») — см.
 *     STRONG_GEO_CONTEXT ниже: без него в чужом жанре протяжка уезжала на города и компании;
 *   • СТРОЧНЫЕ В ЭТОМ ЖЕ ДОКУМЕНТЕ гасят омоним. Без этой проверки протяжка размножала
 *     ложняк на весь документ: одно ошибочное «Проектной» давало 182 вхождения, одно
 *     «Земельного» — 57. Настоящее название («Нямдинская», «Новорудный») со строчной
 *     не пишут никогда, а служебное прилагательное — постоянно;
 *   • ГИДРОНИМЫ НЕ ТЯНЕМ. Реки называют по городам («р. Москва», «р. Урал»), и протяжка
 *     ушла бы на сам город — а область, край и столица по решению владельца 01.08 не
 *     маскируются: это не привязка к объекту недр;
 *   • ОСНОВА ОТ ЧЕТЫРЁХ ЗНАКОВ. Короткий огрызок совпадает со слишком многим.
 *
 * ПОЧЕМУ БЕЗ СЛОВАРЯ. Протяжка живёт ВНУТРИ документа и ничего не запоминает между
 * вызовами. Собранный словарь названий пришлось бы хранить в поставке, а это опознаватели
 * клиента в репозитории — ровно то, что здесь запрещено (см. deid/precision.ts о словаре
 * фамилий). Имя, подтверждённое в документе, закрывается в этом же документе — и всё.
 */

import {
  GEO_ADMIN_TAIL,
  GEO_COMMON_NAME,
  GEO_DESCRIPTIVE_ADJ,
  looksLikeGeoName,
  type DetectedEntity,
} from "./detect";

/**
 * ПЕРЕЧИСЛЕНИЕ при одном ключе: «рудные поля Сюрприз, Юбилейное, Зенит-Виктория,
 * Петербургское», «руч. Второй, Удалой, Тундровый», «Экодинского и Чунского участков».
 *
 * Правила ловят имя, стоящее ВПЛОТНУЮ к ключевому слову, поэтому из списка закрывается
 * ровно одно имя — первое (когда ключ слева) или последнее (когда ключ справа). Остальные
 * остаются открытыми, хотя автор перечислил равноправные объекты одного вида. Замер 05.08
 * на публичных гео-корпусах: из 78 настоящих пропусков GEO_NAME так терялись 8, и это
 * второй по величине класс после ручьёв.
 *
 * Ходим В ОБЕ СТОРОНЫ, потому что ключ бывает и слева, и справа. Шаг — только через
 * запятую, точку с запятой или «и»: любое строчное слово между именами обрывает цепочку
 * («участок Северный, расположенный на территории…» дальше не идёт). Кандидат проходит те
 * же проверки, что и имя из правила, — форму слова и три стоп-листа, — иначе перечисление
 * начнёт собирать области и шапки таблиц.
 *
 * Скобка перед разделителем — часть той же строки перечисления, а не её конец:
 * «по гайотам Говорова (кластер 08-3) и Вулканолог (кластер 09-1)». Без неё цепочка
 * обрывалась на первом же уточнении в скобках.
 */
const ENUM_RIGHT = /^(?:\s*\([^)\n]{0,40}\))?(?:\s*[,;]\s*|\s+и\s+)([А-ЯЁ][А-ЯЁа-яё0-9]+(?:-[А-ЯЁа-яё0-9]+)*)/u;
/**
 * НАЛЕВО ходим только через «и», без голой запятой. Проверка на чужих жанрах поймала
 * ровно эту разницу: «г. Москва, Павелецкая площадь, д. 2» — запятая слева от ключа отделяет
 * не соседний участок, а ГОРОД, и левый ход через запятую записывал Москву в гео-имена
 * (13 находок на судебном корпусе и раскрытиях, все одинаковые). Настоящее перечисление
 * перед ключом пишут союзом: «Экодинского И Чунского участков», «Центрального И
 * Порт-Артуровского участков». Направо запятая остаётся: там ключ уже слева, и список за
 * ним однороден по построению фразы.
 */
const ENUM_LEFT = /([А-ЯЁ][А-ЯЁа-яё0-9]+(?:-[А-ЯЁа-яё0-9]+)*)(?:\s*\([^)\n]{0,40}\))?(?:\s*,)?\s+и\s+$/u;
/** Больше шести звеньев подряд перечислением уже не бывает — дальше это таблица. */
const ENUM_MAX_STEPS = 6;

/**
 * Падеж кандидата зависит от того, где стоит ключ. Справа от ключа имя стоит в
 * ИМЕНИТЕЛЬНОМ («рудные поля Сюрприз, Юбилейное»), слева — согласовано с ключом и потому
 * в КОСВЕННОМ («Экодинского и Чунского участков», «Центрального и Порт-Артуровского»).
 * Требовать именительный в обе стороны — значит потерять всю левую половину: именно так
 * «Центрального» и «Экодинского» и терялись при первой сборке правила.
 */
function enumCandidateOk(
  name: string,
  text: string,
  at: number,
  nominative: boolean,
  strongKey: boolean,
): boolean {
  return (
    (strongKey || looksLikeGeoName(name, nominative)) &&
    !ENUM_CLASS_WORD.test(name) &&
    !ENUM_STREET_TAIL.test(text.slice(at + name.length, at + name.length + 24)) &&
    !GEO_COMMON_NAME.test(name) &&
    !GEO_DESCRIPTIVE_ADJ.test(`${name} `) &&
    !GEO_ADMIN_TAIL.test(text.slice(at + name.length, at + name.length + 40))
  );
}

/**
 * Слева от затравки стоит ОДНОЗНАЧНО геологический ключ. После такого ключа правила и сами
 * берут имя ЛЮБОЙ формы (см. detect.ts: «месторождения Ихала»), потому что другого смысла у
 * слова нет, — и перечисление после него имеет то же право. Без этого из списка выпадали
 * имена без узнаваемого суффикса: «гайотам Говорова и ВУЛКАНОЛОГ», «Сюрприз, Юбилейное,
 * ЗЕНИТ-ВИКТОРИЯ». Слабые ключи («участок», «площадь») сюда не входят: там форма — вся защита.
 */
const ENUM_STRONG_KEY =
  /(?<![А-Яа-яЁёA-Za-z])(?:месторождени[а-яё]*|проявлени[а-яё]*|гайот[а-яё]*|рудн[а-яё]*\s+пол[а-яё]*|залеж[а-яё]*|руч\.|ручь[а-яё]*|ручей|рек[аиеуой]|р\.)\s*$/iu;

/**
 * Класс объекта, а не имя: «месторождение Ихала, РЕСПУБЛИКА Карелия». После сильного ключа
 * проверка формы снята, и такие слова прошли бы как названия — они и по форме, и по регистру
 * от имени неотличимы. Список закрытый и короткий: это единицы деления страны и типы
 * населённых пунктов, которые по решению владельца 01.08 не маскируются.
 */
const ENUM_CLASS_WORD =
  /^(?:Республик|Област|Кра[йя]|Округ|Район|Город|Село|Посёлок|Поселок|Станиц|Деревн|Улиц|Федерац|Территор|Муниципал)[а-яё]*$/u;

/**
 * Городская привязка справа от имени: «наб. реки Фонтанки (четная сторона) и АНГЛИЙСКОГО ПР.».
 * Река — сильный ключ, и перечисление после неё берёт имя любой формы, поэтому в список
 * попал проспект: на корпусе сканов это дало 5 находок в одном проекте капремонта моста.
 * Проспект, улица и набережная — не объект недр (решение владельца 01.08: адреса не
 * маскируем), и отличает их слово-тип СПРАВА, а не форма самого имени.
 */
const ENUM_STREET_TAIL =
  /^\s*(?:пр\.|просп\.|проспект|ул\.|улиц|наб\.|набережн|шоссе|пер\.|переул|бул\.|бульвар|пл\.|площадь\s+[А-ЯЁ]|мост|канал|туннел|тоннел|д\.\s*\d)/iu;

/**
 * Имена, дописанные перечислением к каждому подтверждённому гео-имени.
 *
 * Кандидат, не прошедший проверку, цепочку НЕ обрывает — шаг просто пропускается. Иначе
 * одно имя необычной формы («Зенит-Виктория» — ни именительного суффикса, ни топонимного)
 * съедало весь хвост списка вместе с «Петербургское», которое проверку проходит. Границы
 * держат не обрывы, а сами разделители: строчное слово между именами цепочку заканчивает.
 */
function enumerateNeighbours(text: string, e: DetectedEntity): DetectedEntity[] {
  const out: DetectedEntity[] = [];
  const strongKey =
    ENUM_STRONG_KEY.test(text.slice(Math.max(0, e.index - 40), e.index)) ||
    ENUM_STRONG_KEY.test(`${e.raw} `.slice(0, e.raw.length)) ||
    /(?<![А-Яа-яЁёA-Za-z])(?:месторождени|проявлени|гайот|руч\.|ручь|рек[аиеуой]|р\.)/iu.test(e.raw);
  let cursor = e.index + e.raw.length;
  for (let step = 0; step < ENUM_MAX_STEPS; step++) {
    const m = ENUM_RIGHT.exec(text.slice(cursor, cursor + 90));
    if (!m) break;
    const name = m[1]!;
    const at = cursor + m[0].length - name.length;
    if (enumCandidateOk(name, text, at, true, strongKey)) {
      out.push({ type: "GEO_NAME", raw: name, index: at, confidence: "medium", source: "rule" });
    }
    cursor = at + name.length;
  }
  let head = e.index;
  for (let step = 0; step < ENUM_MAX_STEPS; step++) {
    const left = text.slice(Math.max(0, head - 90), head);
    const m = ENUM_LEFT.exec(left);
    if (!m) break;
    const name = m[1]!;
    const at = head - (left.length - m.index);
    if (enumCandidateOk(name, text, at, false, strongKey)) {
      out.push({ type: "GEO_NAME", raw: name, index: at, confidence: "medium", source: "rule" });
    }
    head = at;
  }
  return out;
}

/** Ключевые слова гео-правил: в основу имени не идут. */
const GEO_KEY_WORDS =
  /(?:^|\s)(?:месторождени[а-яё]*|проявлени[а-яё]*|участк[а-яё]*|участок|площад[а-яё]*|недр|уч\.)(?=\s|$)/giu;

/** Гидроним: такие имена не тянем (см. второй ограничитель в шапке файла). */
const HYDRONYM = /^(?:[«"]?р\.|рек[аиеуой])/iu;

/**
 * Слева от имени должен стоять ОДНОЗНАЧНО геологический объект — иначе не тянем.
 *
 * Проверка на судебном корпусе (10 002 решения) показала, зачем: затравка от многозначного
 * ключа уводила протяжку в сторону. «Москва Новая площадь» давала основу «москв» и
 * закрывала 172 упоминания столицы, «площадка «Меркурий»» — 104 упоминания ФГИС, дальше
 * шли «Ивановской», «Ульяновска», «Вайлдберриз»: области, города и компании. Все они
 * пишутся только с заглавной, поэтому ограничитель по строчным их не ловит.
 *
 * «Месторождение», «проявление», «недра» другого смысла не имеют, и после них стоит
 * название объекта недр, а не города. На геологии это сохраняет три четверти выигрыша
 * (157 вхождений из 208), а в чужом жанре протяжка просто не запускается.
 */
const STRONG_GEO_CONTEXT =
  /(?:месторождени[а-яё]*|проявлени[а-яё]*|недр(?:а|ы)?|залеж[а-яё]*|рудник[а-яё]*)\s*[«"]?\s*$/iu;
const CONTEXT_WINDOW = 40;

/** Падежное окончание, которое снимаем, чтобы получить основу. Длинные — первыми. */
const CASE_ENDING =
  /(?:ского|ская|ской|ские|ских|ском|скую|ого|его|ому|ему|ыми|ими|ое|ая|ый|ий|ой|ые|ие|ых|их|ым|им|ом|ем|ей|ую|юю|а|у|е|ы|и)$/u;

const MIN_STEM = 4;

/** Основа имени без падежного окончания: «Нямдинской» → «нямдин». null — не имя. */
function nameStem(word: string): string | null {
  const w = word.replace(/[«»"',.;:()]/gu, "");
  if (!/^[А-ЯЁ]/u.test(w)) return null;
  const stem = w.replace(CASE_ENDING, "");
  return stem.length >= MIN_STEM ? stem.toLowerCase() : null;
}

function stemRe(stem: string, flags: string): RegExp {
  const safe = stem.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
  return new RegExp(`(?<![А-ЯЁа-яё])${safe}[а-яё]{0,4}(?![А-ЯЁа-яё])`, flags);
}

/**
 * Доп. вхождения гео-имён, подтверждённых в этом же документе.
 * Спаны могут пересекаться с уже найденным — вызывающий прогоняет resolveOverlaps.
 */
export function spreadGeoNames(text: string, ents: readonly DetectedEntity[]): DetectedEntity[] {
  const stems = new Set<string>();
  // Перечисление разбираем ПЕРВЫМ: его находки — такие же подтверждённые имена, и дальше
  // они на общих правах уходят в протяжку по документу (в таблице координат имя стоит
  // голым, ключа рядом нет, и закрыть его может только протяжка).
  const enumerated: DetectedEntity[] = [];
  for (const e of ents) {
    if (e.type !== "GEO_NAME") continue;
    enumerated.push(...enumerateNeighbours(text, e));
  }
  for (const e of [...ents, ...enumerated]) {
    if (e.type !== "GEO_NAME" || HYDRONYM.test(e.raw)) continue;
    // Ключ может стоять внутри находки («Новотроицкое месторождение») либо остаться в
    // тексте слева от неё («месторождения Ихала» — правило берёт только имя).
    const left = text.slice(Math.max(0, e.index - CONTEXT_WINDOW), e.index);
    if (!STRONG_GEO_CONTEXT.test(left) && !STRONG_GEO_CONTEXT.test(`${e.raw} `) && !/недр/iu.test(e.raw)) continue;
    for (const word of e.raw.replace(GEO_KEY_WORDS, " ").split(/\s+/u)) {
      const stem = nameStem(word);
      if (stem) stems.add(stem);
    }
  }
  // Омоним: основа, встречающаяся в документе со строчной, — обычное слово, не имя.
  for (const stem of [...stems]) {
    if (stemRe(stem, "gu").test(text)) stems.delete(stem);
  }
  if (!stems.size) return enumerated;

  const out: DetectedEntity[] = [...enumerated];
  for (const stem of stems) {
    for (const m of text.matchAll(stemRe(stem, "giu"))) {
      out.push({
        type: "GEO_NAME",
        raw: m[0],
        index: m.index ?? 0,
        confidence: "medium",
        source: "rule",
      });
    }
  }
  return out;
}
