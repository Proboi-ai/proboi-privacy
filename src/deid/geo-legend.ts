/**
 * ЛЕГЕНДА КАРТЫ: список географических названий под собственным заголовком.
 *
 * ЗАЧЕМ. Распознанная карта приезжает к нам markdown-ом, и место работ в ней перечислено
 * СПИСКОМ БЕЗ КЛЮЧЕЙ — ключ стоит ОДИН РАЗ, в заголовке секции:
 *
 *     ### Основные топографические названия (на карте)
 *     *   Прав. Тюбелях
 *     *   Потерянный
 *     *   пос. Старый Оротук
 *     *   г. Ляглака
 *
 * Все правила detect.ts устроены как «ключ рядом с именем», и такой список не видит ни одно
 * из них: рядом с «Потерянный» нет ничего, кроме звёздочки. Замер 06.08 на буровых журналах
 * недропользователя: это САМЫЙ КРУПНЫЙ класс пропуска GEO_NAME — 41 эталонное имя из 71, то
 * есть больше половины всех пропусков разом, и все они уходили наружу открытыми. Ирония в
 * том, что документ-карта — ровно тот случай, где название местности и есть всё содержание.
 *
 * ПОЧЕМУ ЭТО НЕ РАЗБОР ТАБЛИЦ. Разбирать колонки мы не беремся: там ключ живёт в шапке за
 * тысячи знаков, и связь «шапка → ячейка» правилом не выражается. Здесь же разметка отдаёт
 * структуру даром: заголовок — это строка с `#` либо строка-подпись с двоеточием, элемент —
 * строка с маркером списка. Ни первое, ни второе искать не нужно, оно уже размечено.
 *
 * ГРАНИЦЫ. Секционное правило опасно тем, что открывает СРАЗУ ВЕСЬ список, поэтому границ
 * две, и каждая проверена на реальных легендах из архива клиента:
 *
 *  1. ЗАГОЛОВОК. Берём формулировки, которые обещают перечень подписей карты:
 *     «топографические названия», «обозначения на карте», «подписи на схеме», «условные
 *     обозначения». Последнее — самое широкое и само по себе НИЧЕГО не обещает: под ним в
 *     геологической легенде перечислены породы, индексы фаз и пояснения к значкам
 *     («γτJ3sb5: Вторая фаза диорит-порфиритов»). Держит его не заголовок, а граница 2:
 *     проверено на двух реальных легендах этого вида (doc-051, doc-028) — из них не проходит
 *     НИ ОДИН элемент, а из третьей (doc-042) проходит ровно название прииска.
 *  2. ЭЛЕМЕНТ ПРОВЕРЯЕТСЯ ОТДЕЛЬНО. Даже внутри правильной секции строка обязана выглядеть
 *     как имя собственное: коротко, без пояснения через двоеточие, без комментария в
 *     скобках, без перечня кодов через запятую, и КАЖДОЕ слово в ней — либо родовой
 *     географический термин («г.», «пос.», «руч.», «Зона»), либо слово с заглавной, либо
 *     номер. Одно строчное слово внутри — и это уже описание значка, а не название:
 *     «Точка наблюдения», «Линии профиля с пунктами наблюдения», «Разрывные нарушения»
 *     отсеиваются именно так.
 *
 * Замер после правки: полнота GEO_NAME на буровых журналах клиента 69,4 → 96,1 %, на
 * публичных гео-корпусах без изменений (84,4 %), на чужих жанрах (400 судебных решений и
 * 1500 раскрытий, 12 млн знаков) — НИ ОДНОЙ новой находки.
 */

/** Спан в координатах поданного текста. */
export interface LegendName {
  index: number;
  raw: string;
}

/**
 * Заголовок, который обещает СПИСОК НАЗВАНИЙ.
 *
 * Две формы, обе встречены в архиве недропользователя: «Основные топографические названия
 * (на карте)» и «Обозначения на карте:». Родовое «Условные обозначения» без «на карте» под
 * шаблон не подходит намеренно — см. границу 1 в шапке файла.
 */
const LEGEND_HEADING =
  /(?:топографическ|географическ|топоним|гидроним)[а-яё]*\s+(?:названи|наименовани)|(?:названи|наименовани|обозначени|подпис)[а-яё]*\s+(?:географическ[а-яё]*\s+)?(?:объектов\s+)?на\s+(?:карте|плане|схеме)|условны[ех]\s+обозначени/iu;

/** Строка-заголовок markdown: `### Текст`. */
const MD_HEADING = /^\s{0,3}#{1,6}\s+(.+?)\s*$/u;
/** Строка-подпись: «Обозначения на карте:» — заголовок без решёток, но с двоеточием. */
const LABEL_LINE = /^\s{0,3}(\S.{0,78}?)\s*:\s*$/u;
/** Горизонтальная черта — конец секции. */
const RULE_LINE = /^\s{0,3}(?:[-*_=]\s?){3,}$/u;
/** Элемент списка: маркер и текст за ним. */
const BULLET = /^\s{0,6}(?:[*•‣·+]|[-–—]|\d{1,2}[.)])[ \t]+(\S.*?)\s*$/u;

/** Длиннее — это уже пояснение к значку, а не название. */
const ITEM_MAX_LEN = 44;
/** Не больше трёх слов: «пос. Старый Оротук» — предел настоящего названия в легенде. */
const ITEM_MAX_WORDS = 3;
/**
 * Знак, которого в названии не бывает.
 *  • двоеточие — пояснение к условному знаку («K-1701: Канавы пройденные 2017 г.»);
 *  • скобка — комментарий разметки («K3124, K3123 (обозначения участков/выработок)»);
 *  • запятая — перечень служебных шифров, а не одно имя;
 *  • труба — строка таблицы, секция к этому моменту уже кончилась.
 */
const ITEM_BAD_CHAR = /[:()|«»"'\\/,;=<>[\]{}]/u;

/**
 * Родовой географический термин. В названии он стоит служебным словом («г. Ляглака»,
 * «Зона Медная»), поэтому со строчной буквы и с точкой на конце допустим — в отличие от
 * любого другого строчного слова, которое означает, что перед нами описание.
 */
const GENERIC_TERM = new Set([
  "г.", "гор.", "пос.", "п.", "с.", "д.", "дер.", "ст.", "оз.", "р.", "рч.", "руч.", "кл.",
  "ур.", "пер.", "прав.", "лев.", "верх.", "ниж.", "мал.", "бол.", "б.", "в.", "зал.", "бух.",
  "зона", "участок", "уч.", "гора", "сопка", "ручей", "река", "речка", "озеро", "падь",
  "ключ", "распадок", "лог", "хребет", "перевал", "мыс", "остров", "о.", "протока", "приток",
]);

/** Слово годится в название: родовой термин, номер либо слово с заглавной. */
function tokenLooksLikeName(token: string): boolean {
  if (GENERIC_TERM.has(token.toLowerCase())) return true;
  if (/^\d{1,4}[а-яёa-z]?$/iu.test(token)) return true;
  return /^[А-ЯЁ][А-Яа-яЁё-]*\.?$/u.test(token);
}

/** Хвостовая пунктуация в спан не идёт: «Приисковое Колпаковое.» → «Приисковое Колпаковое». */
function trimTail(item: string): string {
  return item.replace(/[.,;\s]+$/u, "");
}

/**
 * Строка списка — это название местности.
 *
 * Проверка идёт ПО КАЖДОМУ СЛОВУ, а не по стоп-листу: перечислить все описания значков
 * невозможно, а вот отличить «Дождливый» от «Точка наблюдения» по форме слов — можно.
 * Одно строчное слово, не входящее в короткий список родовых терминов, отменяет находку.
 */
export function legendItemIsName(item: string): boolean {
  const value = trimTail(item);
  if (value.length < 2 || value.length > ITEM_MAX_LEN) return false;
  if (ITEM_BAD_CHAR.test(value)) return false;
  if (!/[А-ЯЁ]/u.test(value)) return false;
  const tokens = value.split(/[ \t ]+/u);
  if (tokens.length > ITEM_MAX_WORDS) return false;
  if (!tokens.every(tokenLooksLikeName)) return false;
  // Родовой термин сам по себе именем не является: «Зона», «руч.» без имени — это подпись
  // столбца легенды, а не объект.
  return tokens.some((t) => !GENERIC_TERM.has(t.toLowerCase()));
}

/**
 * Названия из секций-легенд поданного текста.
 *
 * Спан берётся на ВЕСЬ элемент списка вместе с родовым термином («г. Ляглака»): термин
 * стоит вплотную к имени и в выдаче без него читается как обрывок. Ровно так же поступают
 * правила гидронимов в detect.ts.
 */
export function detectLegendNames(text: string): LegendName[] {
  const out: LegendName[] = [];
  let inSection = false;
  let at = 0;
  for (const line of text.split("\n")) {
    const lineStart = at;
    at += line.length + 1;

    const heading = MD_HEADING.exec(line) ?? LABEL_LINE.exec(line);
    if (heading) {
      inSection = LEGEND_HEADING.test(heading[1]!);
      continue;
    }
    if (!inSection) continue;
    if (!line.trim()) continue;
    if (RULE_LINE.test(line)) {
      inSection = false;
      continue;
    }
    const bullet = BULLET.exec(line);
    if (!bullet) {
      // Обычный абзац или строка таблицы — список кончился.
      inSection = false;
      continue;
    }
    const item = bullet[1]!;
    if (!legendItemIsName(item)) continue;
    const value = trimTail(item);
    out.push({ index: lineStart + line.indexOf(item), raw: value });
  }
  return out;
}
