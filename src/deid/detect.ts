// ─── Инициалы: к какому слову они относятся ──────────────────────────────────
//
// «Слово И.О. Слово» читается двумя способами — «Фамилия И.О.» и «И.О. Фамилия», — и по
// форме они неразличимы: «Отчёт составил Иванов И.П. Задание направлено…» против
// «Утвердил А.С. Петров». Различает их ровно один признак: ИНФОРМАТИВНА ЛИ ЗАГЛАВНАЯ БУКВА
// у слова слева от инициалов. «Иванов» стоит посреди фразы — заглавная там значит «имя
// собственное». «Утвердил» стоит в начале строки — заглавная навязана позицией и не значит
// ничего. Отсюда два симметричных фильтра ниже; словарь слов для этого не нужен.

/** Строка состоит только из отступа и маркера списка — заглавная после неё вынужденная. */
const LINE_LEAD_ONLY = /^[\s\d.)(•‣*·>|–—-]*$/u;

/** Конец предложения непосредственно перед словом — заглавная после него вынужденная. */
const SENTENCE_END_BEFORE = /[.!?…][»"')\]]?\s*$/u;

/** Заглавная в позиции `index` навязана позицией (начало строки/пункта/предложения). */
function capitalIsForced(text: string, index: number): boolean {
  const line = text.slice(text.lastIndexOf("\n", index - 1) + 1, index);
  return LINE_LEAD_ONLY.test(line) || SENTENCE_END_BEFORE.test(line);
}

/** Слово перед инициалами, годное в фамилии. Окно ограничено строкой — ФИО её не пересекает. */
const SURNAME_BEFORE = new RegExp(`(?<![А-Яа-яЁё-])${SURNAME}[ \\u00a0\\t]+$`, "u");

/** Заглавное слово сразу после инициалов, годное в фамилии. */
const SURNAME_AFTER = /^[  \t]?[А-ЯЁ][а-яё]/u;

/**
 * Слева от инициалов стоит слово, которое читается как фамилия: заглавное И с
 * информативной заглавной. Тогда инициалы принадлежат ему, а не слову справа.
 */
function surnamePrecedes(text: string, index: number): boolean {
  const from = Math.max(text.lastIndexOf("\n", index - 1) + 1, index - 96);
  const m = SURNAME_BEFORE.exec(text.slice(from, index));
  return m !== null && !capitalIsForced(text, from + m.index);
}

/**
 * Вплотную к спану стоит заглавное слово, годное в имя или фамилию, — значит спан лишь
 * ЧАСТЬ более длинного ФИО. Должности не в счёт: «Ответственный Петрович» — это отчество
 * при роли, а не двусловное имя.
 */
/** Слева вплотную стоит заглавное слово, годное в имя или фамилию (должности не в счёт). */
function nameWordPrecedes(text: string, index: number): boolean {
  const before = /([А-ЯЁ][а-яё]+)[  \t]+$/u.exec(text.slice(Math.max(0, index - 48), index));
  return before !== null && !ROLE_WORDS.has(before[1]!.toLowerCase());
}

function nameWordTouches(text: string, index: number, length: number): boolean {
  if (nameWordPrecedes(text, index)) return true;
  const after = /^[  \t]+([А-ЯЁ][а-яё]+)/u.exec(text.slice(index + length, index + length + 48));
  return after !== null && !ROLE_WORDS.has(after[1]!.toLowerCase());
}

/**
 * Фильтр правила «Фамилия И.О.»: уступить форме «И.О. Фамилия» ТОЛЬКО когда слово слева не
 * может быть фамилией по позиции. Раньше здесь стоял безусловный lookahead — из-за него
 * «Иванов И.П. Задание» не матчилось вовсе, фамилия оставалась в тексте открытой, а в сейф
 * как человек попадало «И.П. Задание».
 */
function surnameBindsLeft(raw: string, text: string, index: number): boolean {
  if (!capitalIsForced(text, index)) return true;
  const end = index + raw.length;
  return !SURNAME_AFTER.test(text.slice(end, end + 3));
}

/**
 * Отличает НОМЕР скважины от числа, которое просто стоит рядом со словом.
 *
 * Замер 04.08 на корпусе ЕИС: из 327 находок WELL 116 были без «№», и среди них вперемешку
 * настоящие номера («Скв. Х-3132», «скв. 11», «Скв. ХБ-149» — сокращение с точкой это
 * нормальная форма записи) и мусор четырёх видов. Мусор и отсекаем:
 *   • год — «скважина 2024г», «скважин 2023 г.»: цифра рядом, но это не идентификатор;
 *   • пункт документа — «скважин п.1A», «скважин: т.57»: префиксы «п.»/«т.» перед номером;
 *   • нумерация раздела — «скважин 1.3.», «скважин. 2.2.3.»: две и более точки-разделителя;
 *   • новое предложение — «скважины. 20», «скважины 4.провести»: точка стоит после ПОЛНОГО
 *     слова, значит число относится уже к следующей фразе, а не к скважине. У сокращения
 *     «скв.» точка своя, часть записи, и такой проверке не подлежит.
 * Наличие «№» перевешивает всё: автор явным знаком сказал, что это номер.
 */
function isWellNumber(raw: string): boolean {
  if (/№/.test(raw)) return true;
  const parts = raw.match(/^(скважин[а-яё]*|скв\.?|буров(?:ая|ой|ую))\s*([:.]?)\s*(.*)$/iu);
  if (!parts) return true;
  const [, key, separator, num] = parts as unknown as [string, string, string, string];

  // Точка после ПОЛНОГО слова = конец предложения, число относится уже к следующей фразе.
  // У сокращения «скв.» точка своя — она часть записи, а не знак конца.
  if (separator === "." && /^скважин/iu.test(key)) return false;
  // Пункт/таблица документа: «п.1A», «т.57».
  if (/^[птПТ]\s*\./u.test(num)) return false;
  // Нумерация раздела «1.3.», «2.2.3.» — две и более точки.
  if ((num.match(/\./g) ?? []).length >= 2) return false;
  // «4.провести» — цифра, точка и сразу слово: пункт списка.
  if (/^\d+\.[А-Яа-яЁёA-Za-z]/u.test(num)) return false;
  // Год: «2024г» или голые четыре цифры в диапазоне лет.
  const digits = num.replace(/\D/g, "");
  const year = parseInt(digits, 10);
  if (/^\d{4}\s*г/iu.test(num)) return false;
  if (digits.length === 4 && year >= 1900 && year <= 2100 && !/[-/A-Za-zА-Яа-яЁё]/u.test(num)) return false;
  // Голое число с точкой на конце — пункт списка: «скважины 1. Общие положения».
  // У настоящего номера есть буква или дефис («Скв. Х-3132.»), и его это не задевает.
  if (/^\d+\.$/u.test(num)) return false;
  // Родительный падеж множественного числа + голое число = СЧЁТ ШТУК, не номер:
  // «скважин 7 и 19 с возможностью водоотбора». У номера в этой форме автор ставит
  // «№» («скважин №74,26,50»), и такая запись сюда не доходит — она отсеяна выше.
  if (/^скважин$/iu.test(key) && /^\d+$/u.test(num)) return false;
  return true;
}

