/**
 * Форма имени геологического объекта.
 *
 * Правила «ключ + имя» ловили ЛЮБОЕ слово с заглавной рядом с ключевым словом, а с
 * заглавной в документе стоит каждое первое слово предложения и каждая шапка столбца.
 * Замер 04.08 на корпусе ЕИС: «земельного участка Провести обследование» → маскировалось
 * «Провести», «Периметр Площадь Диаметр Длина» → «Диаметр», и таких находок набралось
 * больше, чем настоящих названий.
 *
 * Разделяет их форма слова, а не список. Названия объектов недр в русском —
 * прилагательные («Кварцевое», «Приморский», «Нямдинская»), топонимы на -ово/-ево/-ино
 * и -ск/-цк («Батырево», «Мурманск») либо буквенно-цифровые коды блоков («В1-5»).
 * Обычные существительные и глаголы («Диаметр», «Отделка», «Стоимость», «Провести»)
 * ни одной из этих форм не имеют.
 *
 * Форм две, и различает их падеж. ПЕРЕД ключом имя согласовано с ним и стоит в косвенном
 * падеже («Нямдинской площади», «Приморского месторождения») — там нужен полный набор
 * окончаний. ПОСЛЕ ключа падеж несёт сам ключ, а имя остаётся в именительном («участок
 * Северный», «месторождение Кварцевое») — и полный набор там только вредит: дательное
 * «-ему» пропускало винительное существительное «Схему» («участка Схему размещения»).
 *
 * Отдельно отсекаются отглагольные существительные на -ание/-ение: «Значение», «Описание»,
 * «Месторасположение» кончаются на «-ие» и по окончанию неотличимы от прилагательного,
 * а названием объекта не бывают никогда.
 */
/**
 * Падежи существительного «участок». Перечислены явно, потому что шаблон «участк[а-яё]+»
 * захватывал ещё и ПРИЛАГАТЕЛЬНОЕ «участковый»: на судебном корпусе это давало
 * «Куйтунского участкового лесничества» — лесничество, а не участок недр.
 */
const UCHASTOK_FORMS = "участок|участк(?:а|е|и|у|ом|ов|ам|ами|ах)";

/**
 * Имя, за которым следует административная единица: «Ленинского СУДЕБНОГО РАЙОНА»,
 * «Куйтунского УЧАСТКОВОГО ЛЕСНИЧЕСТВА». Название района, округа или лесничества —
 * не объект недр. Замер на судебном корпусе 05.08: без этого запрета правило собирало
 * имена всех районов страны (41 «Ленинского», 38 «Свердловского», …).
 */
export const GEO_ADMIN_TAIL = /^\s*(?:судебн|районн|участков)?[а-яё]*\s*(?:район|округ|област|кра[йя]|лесничеств|поселени|сельсовет|муниципал)/iu;

/**
 * Геологическое описание СРАЗУ ЗА двоеточием — единственное, что отличает метку строки
 * «**Ветреное:** Главными рудовмещающими структурами…» от фамилии говорящего в судебном
 * протоколе «**Иванов:** пояснил, что…». Список закрытый и состоит из слов, которые в
 * описании рудного объекта стоят всегда, а в чужом жанре не встречаются вовсе.
 */
const GEO_ROW_TAIL =
  /(?:рудовмещающ|рудоконтролирующ|рудн[аоыеи]|локализован|локализуетс|месторожден|залеж|орудене|минерализ|штокверк|шток[еу]|дайк|россып|метасоматоз|прожилк|антиклинал|синклинал|брахи|интруз|кварцев[аоыу])/iu;

/**
 * Спан ПЕРЕЧИСЛЕНИЯ берётся на весь список целиком, поэтому стоп-листы применяются к нему
 * иначе, чем к одиночному имени: список отвергается, только если В НЁМ НЕТ НИ ОДНОГО годного
 * имени. Проверять «ни одного плохого» нельзя — общегеографический стоп-лист пересекается с
 * настоящими названиями объектов: месторождение «Дальнее» на Полярном Урале попадает под
 * «Дальний Восток» и в одиночку уносило с собой соседнее «Новогоднее-Монто».
 */
function enumListHasName(raw: string): boolean {
  return raw
    .split(/\s*(?:,|\sи\s)\s*/u)
    .some(
      (n) =>
        n.length > 1 &&
        !GEO_COMMON_NAME.test(n) &&
        !GEO_ANON_PLACEHOLDER.test(n) &&
        !GEO_DESCRIPTIVE_ADJ.test(`${n} `),
    );
}

/**
 * Место, а не имя: «в ПРЕДЕЛАХ Мунгинского рудного узла», «в ГРАНИЦАХ Нямдинской площади»,
 * «в БАССЕЙНЕ р. Колыма». Оборот стоит прямо перед названием и в обычном тексте пишется со
 * строчной, поэтому правилу не мешает. Мешает он в КАПСОВОМ ЗАГОЛОВКЕ: смягчение регистра
 * (softenAllCaps) делает «ПРЕДЕЛАХ» неотличимым от имени собственного, оно становится первым
 * словом находки — и проверка формы отвергает весь заголовок вместе с настоящим названием.
 * Список закрытый: это предложные существительные места, именами объектов недр они не бывают.
 */
const LOCATIVE_LEAD =
  /^(?:Пределах|Границах|Бассейне|Окрестностях|Контуре|Верховьях|Низовьях|Междуречье|Долине|Районе)\s+/u;

/** Обезличенный текст судебного решения: «ФИО1», «ФИО2» — не имя объекта. */
const GEO_ANON_PLACEHOLDER = /^(?:ФИО|Потерпевш|Свидетел|Обвиняем|Подсудим)[а-яё]*\d*$/u;

const GEO_NAME_TOPONYM = /(?:\d|(?:ов|ев|ёв|ин|ын)[оаы]$|[сц]к[а-яё]{0,3}$)/u;
// «-ой» — тоже именительный мужского рода: «участок Береговой», «участок Голубой».
// Без него эти названия отбрасывались как косвенный падеж (3 пропуска на корпусе ЕИС).
const GEO_NAME_NOMINATIVE = /(?:ое|ый|ий|ой|ая|яя|ее|ые|ие)$/u;
/** Аббревиатура-тип объекта: ЖМК, СОШ, ДОУ, ЗУ, ОКС. Капс без строчных — не имя. */
const GEO_NAME_ABBR = /^[А-ЯЁ][А-ЯЁ0-9-]{1,5}$/u;
const GEO_NAME_OBLIQUE = /(?:ого|его|ому|ему|ым|им|ом|ем|ой|ей|ую|юю|ых|их|ыми|ими)$/u;
const GEO_NAME_VERBAL_NOUN = /(?:ани|ени|овани|ирован)[еяию]$/u;

/** Похоже ли слово на имя объекта недр. `nominativeOnly` — для позиции после ключа. */
export function looksLikeGeoName(word: string, nominativeOnly: boolean): boolean {
  if (GEO_NAME_VERBAL_NOUN.test(word)) return false;
  if (GEO_NAME_TOPONYM.test(word) || GEO_NAME_NOMINATIVE.test(word)) return true;
  return !nominativeOnly && GEO_NAME_OBLIQUE.test(word);
}

