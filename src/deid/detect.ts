const CONF_RANK = { high: 0, medium: 1 } as const;
const SOURCE_RANK = { rule: 0, ner: 1 } as const;

/**
 * Снимает перекрытия: точные правила приоритетнее NER, затем уверенность и длина.
 * Это не даёт широкому вероятностному спану затереть точный номер/идентификатор.
 */
export function resolveOverlaps(entities: DetectedEntity[]): DetectedEntity[] {
  const sorted = [...entities].sort(
    (a, b) =>
      SOURCE_RANK[a.source ?? "ner"] - SOURCE_RANK[b.source ?? "ner"] ||
      CONF_RANK[a.confidence] - CONF_RANK[b.confidence] ||
      b.raw.length - a.raw.length ||
      a.index - b.index,
  );
  const out: DetectedEntity[] = [];
  for (const e of sorted) {
    const end = e.index + e.raw.length;
    if (out.some((kept) => e.index < kept.index + kept.raw.length && kept.index < end)) continue;
    out.push(e);
  }
  return out.sort((a, b) => a.index - b.index);
}

/**
 * Детектит PII указанных типов. Разрешает перекрытия в пользу более раннего/длинного
 * матча (жадно), чтобы «Фамилия И.О.» не распалась на части.
 */
export function detectEntities(text: string, types: EntityType[]): DetectedEntity[] {
  const active = RULES.filter((r) => types.includes(r.type));
  const found: DetectedEntity[] = [];

  // Текст из PDF, DOCX и сканов приходит порченым: перенос по слогам, разрядка, латинские
  // двойники после OCR. Правила пишем на нормальном языке, а нормализация приводит вход к
  // нему (см. normalize.ts). Найденное возвращаем в координаты ИСХОДНОГО текста, поэтому в
  // сейф и в документ всегда попадает то, что в нём реально написано.
  const normalized = normalizeForDetection(text);
  const collect = (haystack: string): void => {
    for (const rule of active) {
      for (const m of haystack.matchAll(rule.re)) {
        if (rule.validate && !rule.validate(m[0], haystack, m.index!)) continue;
        const [from, to] = toSourceSpan(normalized, m.index!, m.index! + m[0].length);
        found.push({
          type: rule.type,
          raw: text.slice(from, to),
          index: from,
          confidence: rule.confidence,
          source: "rule",
        });
      }
    }
  };

  collect(normalized.text);
  // Подписи и штампы набирают капсом («КОВАЛЁВ Д.А.»), а все правила ФИО требуют
  // «Заглавная + строчные». Второй проход по смягчённой копии добирает их, не трогая первый:
  // регистр значим для ORG-форм и адресов в верхнем регистре, поэтому смягчённый текст
  // не заменяет исходный, а дополняет его. Длина сохраняется, офсеты общие.
  if (ALL_CAPS_WORD.test(normalized.text)) collect(softenAllCaps(normalized.text));
  // COORD не regex-правило detect.ts — делегируем в специализированный geo/coords
  // (DMS/десятичные градусы/полушария + валидация диапазона lat±90/lon±180). Координата =
  // PII (решение владельца) → токенизируем ДО облака наравне с ФИО/ORG.
  // Координаты ищем по НОРМАЛИЗОВАННОМУ тексту, как и всё остальное. Раньше сюда шёл
  // сырой `text`, и координаты в одиночку оставались без починки OCR-грязи: разрядка
  // («5 6 ° 3 0 '»), латинские двойники, мягкие переносы. Спан возвращаем в исходные
  // координаты через toSourceSpan — в сейф обязано попасть то, что реально написано
  // в документе, иначе ре-идентификация подставит не тот кусок.
  if (types.includes("COORD")) {
    for (const c of detectCoords(normalized.text)) {
      const [from, to] = toSourceSpan(normalized, c.index, c.index + c.raw.length);
      found.push({
        type: "COORD",
        raw: text.slice(from, to),
        index: from,
        confidence: "high",
        source: "rule",
      });
    }
  }
  return resolveOverlaps(found);
}
