// ─── Инициалы: к какому слову они относятся ──────────────────────────────────
//
// «Слово И.О. Слово» читается двумя способами — «Фамилия И.О.» и «И.О. Фамилия», — и по
// форме они неразличимы: «Отчёт составил Иванов И.П. Задание направлено…» против
// «Утвердил А.С. Петров». Различает их ровно один признак: ИНФОРМАТИВНА ЛИ ЗАГЛАВНАЯ БУКВА
// у слова слева от инициалов. «Иванов» стоит посреди фразы — заглавная там значит «имя
// собственное». «Утвердил» стоит в начале строки — заглавная навязана позицией и не значит
// ничего. Отсюда два симметричных фильтра ниже; словарь слов для этого не нужен.

/** Строка состоит только из отступа и маркера списка — заглавная после неё вынужденная. */
const LINE_LEAD_ONLY = /^[\s\d.)(•‣*·>|–—-]*$/u;

/** Конец предложения непосредственно перед словом — заглавная после него вынужденная. */
const SENTENCE_END_BEFORE = /[.!?…][»"')\]]?\s*$/u;

/** Заглавная в позиции `index` навязана позицией (начало строки/пункта/предложения). */
function capitalIsForced(text: string, index: number): boolean {
  const line = text.slice(text.lastIndexOf("\n", index - 1) + 1, index);
  return LINE_LEAD_ONLY.test(line) || SENTENCE_END_BEFORE.test(line);
}

/** Слово перед инициалами, годное в фамилии. Окно ограничено строкой — ФИО её не пересекает. */
const SURNAME_BEFORE = new RegExp(`(?<![А-Яа-яЁё-])${SURNAME}[ \\u00a0\\t]+$`, "u");

/** Заглавное слово сразу после инициалов, годное в фамилии. */
const SURNAME_AFTER = /^[  \t]?[А-ЯЁ][а-яё]/u;

/**
 * Слева от инициалов стоит слово, которое читается как фамилия: заглавное И с
 * информативной заглавной. Тогда инициалы принадлежат ему, а не слову справа.
 */
function surnamePrecedes(text: string, index: number): boolean {
  const from = Math.max(text.lastIndexOf("\n", index - 1) + 1, index - 96);
  const m = SURNAME_BEFORE.exec(text.slice(from, index));
  return m !== null && !capitalIsForced(text, from + m.index);
}

/**
 * Вплотную к спану стоит заглавное слово, годное в имя или фамилию, — значит спан лишь
 * ЧАСТЬ более длинного ФИО. Должности не в счёт: «Ответственный Петрович» — это отчество
 * при роли, а не двусловное имя.
 */
/** Слева вплотную стоит заглавное слово, годное в имя или фамилию (должности не в счёт). */
function nameWordPrecedes(text: string, index: number): boolean {
  const before = /([А-ЯЁ][а-яё]+)[  \t]+$/u.exec(text.slice(Math.max(0, index - 48), index));
  return before !== null && !ROLE_WORDS.has(before[1]!.toLowerCase());
}

function nameWordTouches(text: string, index: number, length: number): boolean {
  if (nameWordPrecedes(text, index)) return true;
  const after = /^[  \t]+([А-ЯЁ][а-яё]+)/u.exec(text.slice(index + length, index + length + 48));
  return after !== null && !ROLE_WORDS.has(after[1]!.toLowerCase());
}

/**
 * Фильтр правила «Фамилия И.О.»: уступить форме «И.О. Фамилия» ТОЛЬКО когда слово слева не
 * может быть фамилией по позиции. Раньше здесь стоял безусловный lookahead — из-за него
 * «Иванов И.П. Задание» не матчилось вовсе, фамилия оставалась в тексте открытой, а в сейф
 * как человек попадало «И.П. Задание».
 */
function surnameBindsLeft(raw: string, text: string, index: number): boolean {
  if (!capitalIsForced(text, index)) return true;
  const end = index + raw.length;
  return !SURNAME_AFTER.test(text.slice(end, end + 3));
}

/**
 * Отличает НОМЕР скважины от числа, которое просто стоит рядом со словом.
 *
 * Замер 04.08 на корпусе ЕИС: из 327 находок WELL 116 были без «№», и среди них вперемешку
 * настоящие номера («Скв. Х-3132», «скв. 11», «Скв. ХБ-149» — сокращение с точкой это
 * нормальная форма записи) и мусор четырёх видов. Мусор и отсекаем:
 *   • год — «скважина 2024г», «скважин 2023 г.»: цифра рядом, но это не идентификатор;
 *   • пункт документа — «скважин п.1A», «скважин: т.57»: префиксы «п.»/«т.» перед номером;
 *   • нумерация раздела — «скважин 1.3.», «скважин. 2.2.3.»: две и более точки-разделителя;
 *   • новое предложение — «скважины. 20», «скважины 4.провести»: точка стоит после ПОЛНОГО
 *     слова, значит число относится уже к следующей фразе, а не к скважине. У сокращения
 *     «скв.» точка своя, часть записи, и такой проверке не подлежит.
 * Наличие «№» перевешивает всё: автор явным знаком сказал, что это номер.
 */
/**
 * Коды территорий в номере лицензии на пользование недрами (Роснедра). Первые три буквы —
 * не произвольные: это закрытый справочник органов, выдающих лицензию.
 *
 * Зачем проверка. Замер 05.08 на документах клиента: детектор принял «ПРК 01204 БР» —
 * это распознавание скана исказило «ИРК» (Иркутск), и получился код, которого не
 * существует. Формат сам по себе три буквы не различает, поэтому любая опечатка и любая
 * ошибка OCR проходили как валидная лицензия и уезжали в выдачу пользователю.
 *
 * Список собран по кодам, реально встреченным в архиве клиента (96 форм), плюс остальные
 * субъекты. Неизвестный код — НЕ находка: лучше пропустить редкий код, чем подтвердить
 * пользователю несуществующий номер лицензии.
 */
const SUBSOIL_REGION_CODES = new Set([
  "АДГ", "АЛТ", "АМУ", "АНД", "АРХ", "АСТ", "БАШ", "БЕЛ", "БЛГ", "БРО", "БРЯ", "ВЛГ", "ВЛВ",
  "ВЛЖ", "ВОЛ", "ВОР", "ГОР", "ДАГ", "ЕКБ", "ИВА", "ИНГ", "ИРК", "КАМ", "КБР", "КЕМ", "КЛГ",
  "КЛМ", "КМН", "КПЯ", "КРД", "КРР", "КРС", "КРЯ", "КУР", "КЧР", "КЗЛ", "ЛЕН", "ЛИП", "МАГ",
  "МАР", "МОР", "МОС", "МСК", "МУР", "НЕН", "НЖГ", "НВС", "НОВ", "ОМС", "ОРБ", "ОРЛ", "ПЕН", "ПЕР",
  "ПРМ", "ПСК", "РОС", "РЯЗ", "САМ", "САР", "САХ", "СВЕ", "СЕВ", "СКЛ", "СМО", "СТА", "СТВ",
  "СЫК", "ТАЛ", "ТАМ", "ТВЕ", "ТОМ", "ТУВ", "ТУЛ", "ТЮМ", "УДМ", "УДЭ", "УЛЬ", "УФА", "ХАБ",
  "ХАК", "ХАН", "ЧЕЛ", "ЧЕР", "ЧИТ", "ЧУК", "ЧУВ", "ШОМ", "ЭВЕ", "ЮГК", "ЮСХ", "ЯКУ", "ЯНЦ",
  "ЯРО",
]);

/** Вид лицензии — второй закрытый справочник: Б/Т/В/Н/Э + Р/П/Э/Т. */
const SUBSOIL_LICENCE_KINDS = /^[БТВНЭК][РПЭТ]$/u;

function isSubsoilLicence(raw: string): boolean {
  const m = raw.match(/^([А-ЯЁ]{3})\s?(?:№\s?)?(\d{5,6})\s?-?\s?([А-ЯЁ]{2})$/u);
  if (!m) return false;
  return SUBSOIL_REGION_CODES.has(m[1]!) && SUBSOIL_LICENCE_KINDS.test(m[3]!);
}

/**
 * Отрезанная половина ДЕСЯТИЧНОГО числа. «Общая глубина скважины 4,8 м», «Отметка устья
 * скважины 1156,4 м» — правило берёт «скважины 4» и «скважины 1156», потому что запятая не
 * входит в класс символов номера, и проверка на дробь (она смотрит внутрь находки) такую
 * запись не видит. Замер 06.08 на буровых журналах клиента: 12 ложных находок из 52
 * неподтверждённых — все эти две фразы. Это тот же класс, что закрыт 05.08 для формы
 * с двоеточием (80c3655), только через запятую и без двоеточия.
 *
 * Смотрим на знак СРАЗУ ЗА находкой: если это разделитель дробной части и за ним цифра —
 * мы разрезали измерение, а не прочитали номер. У настоящего номера там пробел, скобка,
 * конец строки или буква («Скв. 5-Р.»).
 */
function cutsDecimal(raw: string, text: string, index: number): boolean {
  if (/№/u.test(raw)) return false;
  const tail = text.slice(index + raw.length, index + raw.length + 14);
  // «скважины 1,2 и резервуара» — это ПЕРЕЧИСЛЕНИЕ через запятую, а не дробь: одна цифра
  // после запятой и никакой единицы измерения справа. Настоящее измерение выдаёт себя
  // либо единицей («4,8 м»), либо вторым знаком дробной части («1156,45»).
  const m = tail.match(/^[.,](\d+)\s*([а-яё.]{0,3})/u);
  if (!m) return false;
  return m[1]!.length >= 2 || /^(?:м|мм|см|км|м\.)$/u.test(m[2] ?? "");
}

/**
 * Находка стоит в ЯЧЕЙКЕ таблицы: слева, если пропустить пробелы, вертикальная черта (или
 * начало строки), справа — вертикальная черта. Для markdown-таблиц из распознавания это
 * надёжный признак, что перед нами значение колонки, а не кусок фразы.
 */
function inTableCell(raw: string, text: string, index: number): boolean {
  return /(?:^|\n)[^\n|]{0,4}\|[^\n|]{0,4}$/u.test(text.slice(Math.max(0, index - 20), index))
    && /^\s*\|/u.test(text.slice(index + raw.length, index + raw.length + 8));
}

function isWellNumber(raw: string, text?: string, index?: number): boolean {
  if (/№/.test(raw)) return true;
  const parts = raw.match(/^(скважин[а-яё]*|скв\.?|буров(?:ая|ой|ую))\s*([:.]?)\s*(.*)$/iu);
  if (!parts) return true;
  const [, key, separator, num] = parts as unknown as [string, string, string, string];

  // Точка после ПОЛНОГО слова = конец предложения, число относится уже к следующей фразе.
  // У сокращения «скв.» точка своя — она часть записи, а не знак конца.
  if (separator === "." && /^скважин/iu.test(key)) return false;
  // РОДИТЕЛЬНЫЙ ПАДЕЖ + ДВОЕТОЧИЕ = значение свойства, а не имя скважины. По-русски
  // «скважины: 1076.0» читается как «<чего-то> скважины равно 1076.0», и номером быть не
  // может: номер пишут «скважина № 12». Замер 05.08 на отложенном корпусе буровых журналов
  // клиента: 63 находки WELL из 614 (каждая десятая) содержали двоеточие, и ВСЕ до одной
  // оказались измерением — «Отметка устья скважины: 1076.0 м», «Общая глубина скважины: 3.6 м».
  // Именительный падеж («Скважина: 12» — подпись поля в бланке) правилом не задет.
  if (separator === ":" && /^скважины$/iu.test(key)) return false;
  // Дробная часть = метры, а не номер: «Общая глубина скважины 3.6 м», «Отметка устья
  // скважины 1156,4 м». Буквенно-дефисные номера («Скв. Х-3132», «5-бис») проверку не
  // задевают: у них дробной части нет.
  //
  // ИСКЛЮЧЕНИЕ (замер 06.08 на буровых журналах клиента). Разбор 06.08 записал «Скв. 0.2»
  // в мусор распознавания — это была ошибка. В журнале россыпи doc-005 колонка называется
  // «Номер выработки», и ряд идёт …| Скв. 6 | Скв. 2 | Скв. 0.2 | Скв. 0.6 | Скв. 0.14 |:
  // после нулевой линии счёт продолжается в другую сторону, и точка — часть обозначения,
  // а не десятичная запятая. Признаём такую форму по ТРЁМ условиям сразу:
  //   • ключ — сокращение «скв.» (у глубин и отметок ключ пишут полным словом);
  //   • разделитель ТОЧКА, а не запятая (метры в этих журналах всегда через запятую);
  //   • находка стоит в ячейке таблицы — то есть это значение колонки, а не часть фразы.
  // «Общая глубина скважины 4,8 м» и «Отметка устья скважины 1156,4 м» ни одного из трёх
  // условий не выполняют и остаются отсеянными.
  if (/^\d+[.,]\d/u.test(num.trim())) {
    const cellCode =
      /^скв\.?$/iu.test(key) && /^\d+\.\d/u.test(num.trim()) &&
      text !== undefined && index !== undefined && inTableCell(raw, text, index);
    if (!cellCode) return false;
  }
  // Пункт/таблица документа: «п.1A», «т.57».
  if (/^[птПТ]\s*\./u.test(num)) return false;
  // Нумерация раздела «1.3.», «2.2.3.» — две и более точки.
  if ((num.match(/\./g) ?? []).length >= 2) return false;
  // «4.провести» — цифра, точка и сразу слово: пункт списка.
  if (/^\d+\.[А-Яа-яЁёA-Za-z]/u.test(num)) return false;
  // Год: «2024г» или голые четыре цифры в диапазоне лет.
  const digits = num.replace(/\D/g, "");
  const year = parseInt(digits, 10);
  if (/^\d{4}\s*г/iu.test(num)) return false;
  if (digits.length === 4 && year >= 1900 && year <= 2100 && !/[-/A-Za-zА-Яа-яЁё]/u.test(num)) return false;
  // Голое число с точкой на конце — пункт списка: «скважины 1. Общие положения».
  // У настоящего номера есть буква или дефис («Скв. Х-3132.»), и его это не задевает.
  if (/^\d+\.$/u.test(num)) return false;
  // Нулевой номер скважины бывает — и в буровых журналах россыпей он обычный: счёт линий
  // ведут от НУЛЕВОГО пикета, поэтому «Линия 440, скважина 0» и «19-20 (Скважина 0)» —
  // настоящие обозначения. Но «скв. 0» и «скважины 0» в тех же документах — ячейка таблицы
  // (счётчик, отметка «нет данных»): замер 05.08 дал 49 таких ложняков из 3979.
  // Разделяем по ФОРМЕ КЛЮЧА: именительный падеж полного слова («скважина 0») — так автор
  // НАЗЫВАЕТ скважину; сокращение и косвенные падежи — так он что-то ПРО неё сообщает.
  if (/^0+$/u.test(num.trim()) && !/^скважина$/iu.test(key)) return false;
  // Родительный падеж множественного числа + голое число = СЧЁТ ШТУК, не номер:
  // «скважин 7 и 19 с возможностью водоотбора». У номера в этой форме автор ставит
  // «№» («скважин №74,26,50»), и такая запись сюда не доходит — она отсеяна выше.
  if (/^скважин$/iu.test(key) && /^\d+$/u.test(num)) return false;
  return true;
}

