/**
 * Замер ПОЛНОТЫ гео-детекторов «сетью-подсказкой» — без внешних судей.
 *
 * Зачем так. Полноту по геологии не мерили ни разу (замер 01.08 мерил только
 * точность), а тексты клиентских отчётов машину клиента не покидают — внешним
 * LLM-судьям их отдавать нельзя. Поэтому эталон строится ЛОКАЛЬНО: независимый
 * набор нарочно грубых, жадных паттернов («сеть») размечает всё, что ПОХОЖЕ на
 * гео-сущность. Дальше текст прогоняется через боевой детектор с маскированием,
 * и сеть запускается по ИТОГОВОМУ тексту: всё, что она нашла в обезличенном
 * тексте — кандидат в пропуск (значение осталось открытым).
 *
 * Что значит цифра. Сеть шире боевого детектора и ловит в том числе то, что
 * маскировать не надо. Поэтому «полнота относительно сети» — НИЖНЯЯ оценка:
 * реальная полнота не хуже неё, а каждый кандидат в пропуск требует ручного
 * разбора (примеры остаются на машине — наружу только счётчики).
 *
 * Тот же приём, что замер не-именных ПДн 03.08 («телефон с подсказкой»):
 * методика уже показала себя — телефоны 66,5%→99,18% после четырёх правок.
 *
 * ВАЖНО: паттерны сети написаны НЕЗАВИСИМО от src/deid/detect.ts и нарочно
 * грубее. Не «улучшать» их до боевых правил — замер станет циркулярным
 * (детектор будет мериться сам о себя).
 */

import { detectEntities, type DetectedEntity, type EntityType } from "./deid/detect";
import { entitiesForVertical } from "./deid/entities";

/** Гео-типы, полноту которых меряем. */
export const GEO_RECALL_TYPES = ["WELL", "COORD", "LICENSE_SUBSOIL", "GEO_NAME", "CADASTRE"] as const;
export type GeoRecallType = (typeof GEO_RECALL_TYPES)[number];

/**
 * Сеть-подсказка: жадные паттерны по типам. Флаг g обязателен.
 * Формы взяты из замера 01.08 на 170 реальных отчётах EC: доминирующая запись
 * координат — «56°30'с.ш. 108°45'в.д.», скважины — «скв. №4» и «скважина 33-Р»,
 * лицензии — «ЯКУ 12345 НР», названия — «Марковское месторождение», «р. Лена».
 */
export const GEO_RECALL_NET: Record<GeoRecallType, RegExp[]> = {
  WELL: [
    // «скважина/скв.» + идентификатор, в котором ЕСТЬ ЦИФРА.
    //
    // Без требования цифры замер полноты скважин был бессмысленным. Сеть считала
    // пропуском любое слово рядом с ключом («скважины передать», «скважинам», «скважин м»),
    // а маскируем мы НОМЕРНЫЕ скважины — решение владельца 01.08: без номера 82% находок
    // оказались ложняками, правило маскировало соседние обычные слова, ничего не защищая.
    // Итог: 14,4% «полноты» на корпусе ЕИС мерили не скважины, а частоту слова.
    // Цифра — минимальное требование к идентификатору, и сеть остаётся ШИРЕ боевого
    // правила: год («скважин 2024 г.»), пункт документа («скважин п.1А») и нумерацию
    // раздела она по-прежнему считает номером, а детектор их отсекает (isWellNumber).
    /скв(?:ажин[а-яё]*|\.)\s*(?:№\s*)?(?=[\w\dА-ЯЁа-яё./-]{0,12}\d)[\w\dА-ЯЁа-яё][\w\dА-ЯЁа-яё\-/.]{0,11}/giu,
  ],
  COORD: [
    // градусы-минуты(-секунды) в любой записи
    /\d{1,3}\s?[°º]\s?\d{1,2}\s?[′'’]\s?(?:\d{1,2}(?:[.,]\d+)?\s?[″"”])?/gu,
    // Русские полушария — якорь, но только если СЛЕВА рядом есть число, отделённое от
    // сокращения хотя бы одним знаком. Две проверенные формы мимо:
    //   • шапка таблицы «Альтитуда устья, м с.ш. в.д.» — подпись столбцов, значения ниже;
    //   • «ø159в.д.» — диаметр трубы высокого давления, «в.д.» тут вообще не долгота.
    // Обе давали «пропуски» там, где маскировать нечего (12 из 29 на корпусе ЕИС).
    /(?<=\d[^\dА-Яа-яЁёA-Za-z]{1,12})(?:[сСюЮ]\.\s?ш\.|[вВзЗ]\.\s?д\.)/gu,
    // десятичная пара с 4+ знаками после запятой
    /-?\d{1,3}[.,]\d{4,}\s*[,;]\s*-?\d{1,3}[.,]\d{4,}/gu,
    // СК-42/МСК: X=/Y= и кириллические Х=/У=. Целая часть 6–8 цифр — это метры от
    // осевого меридиана. Без ограничения длины сеть ловила сметные формулы
    // «Х=0.52 (куб.м/час)» и объявляла их пропущенными координатами: замер 04.08 дал
    // 86 таких фантомов из 112 «пропусков», то есть измеритель врал про полноту.
    // Считаем именно ЦИФРЫ (6–9), пробелы между ними допускаем: метры пишут и
    // «Х=6254300», и «Х=6 254 300,15». Порог по цифрам, а не по длине строки —
    // иначе сметное «Х = 1 5 0 0 0 (п.м)» с разрядкой проходит как координата и
    // измеритель записывает в пропуски то, что детектор правильно не берёт.
    // Ещё одна форма сметы, которую порог по цифрам не отсекает: X — переменная в формуле
    // расчёта цены, «X = 496 370,82 руб.». Шесть цифр, разряды пробелами — по виду абсцисса
    // СК-42. Отличает её единица измерения справа: у координаты стоят метры или ничего,
    // у денег — «руб.». Заглядываем вперёд через сами цифры, иначе движок откатится на
    // более короткое совпадение и запрет не сработает.
    /[XxYyХхУу]\s*=\s*-?(?:\d\s*){6,9}(?:[.,]\d+)?(?!\d)(?![\s\d.,]{0,12}(?:руб|₽|тыс\.|млн))/gu,
  ],
  LICENSE_SUBSOIL: [
    // серия-номер-вид: ЯКУ 12345 НР
    /[А-ЯЁ]{3}\s?\d{5}\s?[А-ЯЁ]{2}\b/gu,
    // слово «лицензия» + буквенно-цифровой номер рядом
    /лицензи[а-яё]*\s+(?:№\s*)?[А-ЯЁ]{2,4}[\s-]?\d{3,6}/giu,
  ],
  GEO_NAME: [
    // ключ-слово + Имя: «месторождение Хххх», «участок Хххх», «площадь Хххх».
    //
    // «Площадка» вычеркнута из ключей: это ДРУГОЕ слово. Участок недр в проектах ГРР
    // называют «площадью» (существительное), а «площадка» — строительная, лестничная,
    // контейнерная, и к недрам отношения не имеет. С ключом «площад[а-яё]*» сеть
    // записала в пропуски 154 строки вида «на площадке Набор», «площадку ТКО»,
    // «площадка ВФСК ГТО» — маскировать там нечего, а полнота из-за них падала.
    /(?:месторожден[а-яё]*|участ(?:ок|ка|ке|ку|ком)|проявлен[а-яё]*|площад(?:ь|и|ью|ей|ям|ями))\s+[«"]?[А-ЯЁ][\w\dА-ЯЁа-яё-]+/gu,
    // Имя-прилагательное + ключ-слово: «Марковское месторождение»
    /[А-ЯЁ][а-яё-]+(?:ое|ая|ий|ый|его|ого|ской|ского)\s+(?:месторожден[а-яё]*|площад(?:ь|и|ью|ей)|участк[а-яё]*)/gu,
    // реки: решение владельца 01.08 — маскируем. \b не годится: ASCII-граница
    // не видит кириллицу, поэтому lookbehind на не-букву.
    /(?<=^|[^А-ЯЁа-яё])(?:р\.\s?[А-ЯЁ][а-яё-]+|рек(?:а|и|е|у|ой)\s+[А-ЯЁ][а-яё-]+)/gu,
  ],
  CADASTRE: [/\b\d{2}:\d{2}:\d{6,7}:\d{1,5}\b/gu],
};

/**
 * Что сеть находит, но пропуском не считает. Отдельным списком, а не усложнением
 * паттернов: запрет относится ко всем формам типа сразу.
 *
 * GEO_NAME — определение-описание вместо имени. Слово с заглавной в начале предложения
 * или ячейки таблицы выглядит именем собственным для любого паттерна («Общая площадь»,
 * «Полезная площадь»): на корпусе ЕИС это 235 строк, где маскировать нечего.
 * Список лексический — это существительные-признаки, а не имена; он не повторяет
 * решений боевого правила о том, ЧТО маскировать.
 *
 * COORD — нулевые градусы. «(0°0’0”)» в требованиях к оформлению отчёта — это образец
 * записи угловых величин, а «0,00048; 0,00012» — яркости испытательных объектов.
 * Точка с нулевыми координатами не место на карте.
 */
export const GEO_RECALL_NET_REJECT: Partial<Record<GeoRecallType, RegExp>> = {
  GEO_NAME:
    /^(?:общ|полезн|расчётн|расчетн|лестничн|строительн|ориентировочн|жил|нежил|суммарн|отапливаем|застроенн|озелен|рабоч|техническ|складск|торгов|производственн|арендуем|занимаем|максимальн|минимальн|фактическ|проектн|планируем|данн|указанн|исследуем|крыт|детск|спортивн|контейнерн|асфальтированн|бетонн|смотров|зелен|прилегающ|свободн|застраиваем|осваиваем|нарушенн|земельн)[а-яё]{0,4}\s/iu,
  COORD: /^0\s*[°º]\s*0\s*[′'’]\s*0|^-?0[.,]\d+\s*[,;]\s*-?0[.,]/u,
};

/**
 * Все находки сети по типу — единственная точка правды для всех замеров
 * (последовательного и параллельного). Раньше параллельный скрипт ходил в
 * GEO_RECALL_NET напрямую и запрет из GEO_RECALL_NET_REJECT прошёл бы мимо него.
 */
export function geoNetMatches(type: GeoRecallType, text: string): { value: string; index: number }[] {
  const reject = GEO_RECALL_NET_REJECT[type];
  const out: { value: string; index: number }[] = [];
  for (const re of GEO_RECALL_NET[type]) {
    re.lastIndex = 0;
    for (const m of text.matchAll(re)) {
      if (reject?.test(m[0])) continue;
      out.push({ value: m[0], index: m.index ?? 0 });
    }
  }
  return out;
}

export interface GeoRecallLeak {
  type: GeoRecallType;
  /** Что осталось открытым в итоговом тексте. НЕ отдавать наружу — только локальный разбор. */
  value: string;
  /** Контекст вокруг пропуска в обезличенном тексте. Тоже только локально. */
  context: string;
}

export interface GeoRecallPerType {
  /** Находок сети в исходном тексте. */
  вИсходном: number;
  /** Находок сети в обезличенном тексте = кандидаты в пропуск. */
  осталосьПослеМаски: number;
  /** 1 − осталось/вИсходном; null, если сеть в исходном ничего не нашла. */
  полнотаPct: number | null;
}

export interface GeoRecallReport {
  документов: number;
  типы: Record<GeoRecallType, GeoRecallPerType>;
  /** Примеры пропусков (cap задаёт вызывающий). Наружу не отдавать. */
  примерыПропусков: GeoRecallLeak[];
  методика: string;
}

const netMatches = geoNetMatches;

/** Продуктовое маскирование для замера: спаны детектора → [TYPE]. */
export function maskDetected(text: string, entities: DetectedEntity[]): string {
  const sorted = [...entities].sort((a, b) => b.index - a.index);
  let out = text;
  for (const e of sorted) {
    out = out.slice(0, e.index) + `[${e.type}]` + out.slice(e.index + e.raw.length);
  }
  return out;
}

/**
 * Замер полноты на наборе документов. types по умолчанию — вертикаль geo,
 * как в продукте.
 */
export function measureGeoRecall(
  docs: { id: string; text: string }[],
  opts: { types?: EntityType[]; sampleCap?: number } = {},
): GeoRecallReport {
  const detectTypes = opts.types ?? entitiesForVertical("geo");
  const sampleCap = opts.sampleCap ?? 20;

  const totals = Object.fromEntries(
    GEO_RECALL_TYPES.map((t) => [t, { вИсходном: 0, осталосьПослеМаски: 0, полнотаPct: null }]),
  ) as Record<GeoRecallType, GeoRecallPerType>;
  const leaks: GeoRecallLeak[] = [];

  for (const doc of docs) {
    const masked = maskDetected(doc.text, detectEntities(doc.text, detectTypes));
    for (const type of GEO_RECALL_TYPES) {
      totals[type].вИсходном += netMatches(type, doc.text).length;
      for (const m of netMatches(type, masked)) {
        // Матч, зацепивший подставленный токен вида [WELL] — артефакт маски, не пропуск.
        const ctx = masked.slice(Math.max(0, m.index - 60), m.index + m.value.length + 60);
        if (/\[[A-Z_]{3,}\]/.test(m.value)) continue;
        totals[type].осталосьПослеМаски += 1;
        if (leaks.length < sampleCap) {
          leaks.push({ type, value: m.value, context: ctx });
        }
      }
    }
  }

  for (const type of GEO_RECALL_TYPES) {
    const t = totals[type];
    t.полнотаPct = t.вИсходном === 0 ? null : Math.round((1 - t.осталосьПослеМаски / t.вИсходном) * 10000) / 100;
  }

  return {
    документов: docs.length,
    типы: totals,
    примерыПропусков: leaks,
    методика:
      "сеть-подсказка (жадные независимые паттерны) по исходному и обезличенному тексту; " +
      "полнота — НИЖНЯЯ оценка относительно сети; примеры пропусков не покидают машину",
  };
}
