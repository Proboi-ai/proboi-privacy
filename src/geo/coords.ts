/**
 * Детекция географических координат в тексте (ts-spine, без сайдкара).
 *
 * Два независимых семейства, оба высокоточные (мало ложных срабатываний):
 *   • WGS84 — явные координатные пары (с °/N/E/С/В маркерами либо ≥3 знаков
 *     после запятой);
 *   • SK-42 (метровая проекционная, «Система координат 1942 года») — явные
 *     подписи X=/Y= (кириллица-омоглиф Х=/У= тоже — обычное дело в РФ-доках)
 *     либо голая пара 6–8-значных чисел РЯДОМ с явным маркером «СК-42»/
 *     «МСК-NN»/«Пулково-1942». Без якоря (подписи или маркера) метровые числа
 *     НЕ детектим — неотличимы от цены/номера договора/ИНН (тот же приём,
 *     что у LICENSE_SUBSOIL/GEO_NAME в deid/detect.ts: medium-confidence сущность
 *     требует соседнего слова-метки, а не голого числового паттерна).
 *
 * Координата — это PII (решение владельца, council): детектор нужен, чтобы
 * токенизировать её ДО облака. Числовая интерпретация (lat/lon для WGS84,
 * x/y для SK-42) — для «местной СК» (transform.ts) и прочих потребителей;
 * для самой токенизации хватает raw-подстроки, поэтому оба набора полей
 * необязательны.
 */

export interface GeoPoint {
  lat: number; // WGS84 широта, градусы
  lon: number; // WGS84 долгота, градусы
}

export type CoordSystem = "WGS84" | "SK-42";

export interface DetectedCoord {
  raw: string; // исходная подстрока (её и заменяем на токен — round-trip точный)
  index: number; // позиция в тексте
  system: CoordSystem;
  // WGS84: широта/долгота, градусы.
  lat?: number;
  lon?: number;
  // SK-42: абсцисса (X, север) / ордината (Y, восток), метры. Датум-конверсию
  // в WGS84 намеренно не считаем — нужна зона Гаусса-Крюгера, вне зоны этого
  // детектора; для токенизации она и не нужна (см. комментарий вверху файла).
  x?: number;
  y?: number;
}

// Полушария: широта (N/S/С/Ю), долгота (E/W/В/З), оба регистра
const HEMI = "NSEWnsewСЮВЗсювз";
const H_LAT = "NSnsСЮсю";
const H_NEG = "SWswЮЗюз"; // южное/западное → отрицательный знак

// Русские полушария пишут НЕ одной буквой, а сокращением с точками: «56°30'с.ш.
// 108°45'в.д.» — это доминирующая форма в геологических отчётах (замер на реальных
// отчётах EC 2026-08-01: 129 таких пар в выборке из 113 документов, все пропускались).
// Точка после буквы рвала разделитель пары `\s*[,;]?\s+`, поэтому вторая половина
// координаты никогда не подхватывалась и пара не складывалась.
// Регистр второй буквы — любой: «56º27'13,1'' С.Ш., 93º42'25,8'' В.Д.» пишут капсом
// в шапках таблиц и в подписях к схемам (замер 04.08: пара таких пропускалась целиком,
// потому что шаблон требовал строчную «ш»/«д»).
const HEMI_RU_SRC = `(?:[СЮсю]\\s*\\.\\s*[Шш]\\s*\\.|[ВЗвз]\\s*\\.\\s*[Дд]\\s*\\.)`;
/**
 * Суффикс полушария: сокращение с точками ЛИБО одна буква.
 * Одиночная буква обязана стоять отдельным словом: без этого «108°45' снят» съедало
 * «с» от «снят» как «северную широту», подменяло оси и пара отбрасывалась по
 * диапазону (|108.75| > 90). В русском тексте после координаты слово на с/в/ю/з —
 * обычное дело, так что это тихо резало полноту.
 */
const HEMI_SUF_SRC = `(?:${HEMI_RU_SRC}|[${HEMI}](?![А-Яа-яЁёA-Za-z]))?`;
const HEMI_TAIL_RE = new RegExp(`(?:${HEMI_RU_SRC}|[${HEMI}])\\s*$`, "u");
/** Только сокращение с точками — без одиночной буквы (см. isAnchoredDecimalPair). */
const HEMI_RU_RE = new RegExp(HEMI_RU_SRC, "u");
/**
 * Полушарие ГДЕ УГОДНО внутри записи, а не только в хвосте: «55.4093 E 54.8195» — буква
 * стоит МЕЖДУ половинами пары. Замер 05.08: такая запись перестала опознаваться, когда
 * голая пара потеряла запасной путь, — а она самодостаточна, полушарие названо явно.
 * Буква обязана быть отдельным словом (та же граница, что у HEMI_SUF_REQ_SRC), иначе
 * «с»/«в» из обычного русского текста снова начнут работать признаком координаты.
 */
const HEMI_ANYWHERE_RE = new RegExp(
  `(?:${HEMI_RU_SRC}|(?<![А-Яа-яЁёA-Za-z])[${HEMI}](?![А-Яа-яЁёA-Za-z]))`,
  "u",
);

/**
 * Знаки градуса, минуты и секунды — КАЖДЫЙ в нескольких начертаниях.
 *
 * Замер 04.08 на корпусе ЕИС: 22 пропуска подряд оказались координатами вида
 * «17º59'33'' с. ш., 151º59'50'' в. д.» — с ordinal indicator «º» (U+00BA) вместо
 * знака градуса «°» (U+00B0) и двумя апострофами вместо знака секунды «″».
 * Символы визуально неотличимы, набирают их вперемешку, и правило на один
 * канонический знак слепо к половине реальных записей. Секунда как «''» обязана
 * стоять ПЕРЕД одиночными вариантами в чередовании, иначе движок съест один
 * апостроф и оставит второй болтаться.
 */
// Знак ударения «´» (U+00B4) — ещё один двойник апострофа: «45° 39´ 14´´» так печатают
// в переводных каталогах точек (замер 06.08, корпус ЕИС: 11 пропущенных спанов подряд).
// В русском тексте этот знак не употребляется, поэтому добавление ничего не размывает.
const DEG_SIGN = `[°º˚∘]`;
const MIN_SIGN = `['′’‘´]`;
const SEC_SIGN = `(?:''|’’|´´|[″"“”])`;
/** Любой угловой знак в записи — признак того, что число измеряли в градусах, а не считали. */
const ANGLE_SIGN_RE = new RegExp(`${DEG_SIGN}|${MIN_SIGN}|${SEC_SIGN}`, "u");

/**
 * Разделитель «градусы↔минуты». Кроме знака градуса принимаем БУКВУ «о» — кириллическую
 * и латинскую.
 *
 * Замер 05.08 на архиве недропользователя (D:\1.ТПИ, 279 отчётов): из 18 пропущенных
 * координат 7 записаны как «52о19'», «117о28'», «50о40'» — знака градуса нет, вместо него
 * буква. Так набирают с клавиатуры (не переключая раскладку) и так же выходит из
 * распознавания скана: «о» и «°» визуально почти неразличимы.
 *
 * Пробел ПЕРЕД буквой не принимаем, ПОСЛЕ — принимаем, и это не симметрия ради красоты.
 * Слева пробел означает отдельно стоящее слово: «проба 52 о 19' отобрана» — это союз «о»,
 * а не градус, и на таком шаблоне детектор начал бы склеивать координаты из соседних чисел
 * таблицы (зафиксировано отдельным тестом). Справа пробел — это набор «71о 04'», ровно та
 * форма, которой не хватало по замеру 06.08: «о» прилипает к градусам, а минуты отбиты
 * пробелом. Минуты в DMS_CORE_SRC ниже обязаны нести свой знак, и он же держит точность:
 * «52о 19» без апострофа координатой не станет.
 */
const DEG_SEP_SRC = `(?:\\s*${DEG_SIGN}\\s*|[оОoO][ \\u00a0]?)`;

// Разряды DMS одним набором на весь файл. Разъехавшийся дубль шаблона (шаблон поиска и
// шаблон разбора порознь) уже стоил 22 пропусков: строка матчилась правилом, но парсер её
// не разбирал, и пара молча отбрасывалась «меньше двух компонент». Поэтому части общие.
const DEG_NUM = `\\d{1,3}`;
/**
 * Минуты — с дробной частью. «13° 29.883'N 44° 52.859'W» — это градусы-и-десятичные-минуты,
 * штатный формат морской и GPS-привязки; замер 06.08 на корпусе ЕИС дал 28 таких пропусков
 * (проектный участок работ в Атлантике). Шаблон требовал у минут только целое, и вся запись
 * рассыпалась. Знак минуты по-прежнему обязателен — точность держит он, а не число знаков.
 */
const MIN_NUM = `\\d{1,2}(?:[.,]\\d+)?`;
const SEC_NUM = `\\d{1,2}(?:[.,]\\d+)?`;

// Ядро DMS без полушария — нужно и само по себе (диапазоны, см. RANGE_RE ниже).
const DMS_STD_SRC = `${DEG_NUM}${DEG_SEP_SRC}${MIN_NUM}\\s*${MIN_SIGN}\\s*(?:${SEC_NUM}\\s*${SEC_SIGN})?`;
/**
 * OCR-порча, где ВСЕ угловые знаки распознались как открывающая скобка:
 * «57( 43( 18.92((  N» — это «57° 43' 18.92'' N». Целый каталог точек участка приезжает
 * так (замер 06.08, извещения Роснедра: 32 спана в одном документе).
 *
 * Скобка — знак слишком частый, чтобы пускать её в общий класс знаков: «п. 5 (2 (в
 * редакции…» тогда стало бы координатой, а «(в» в русском тексте на каждой странице.
 * Поэтому форма принимается ТОЛЬКО целиком: скобка на месте градуса, минуты И секунды,
 * четыре штуки подряд с цифрами между ними. Такого в обычном тексте не бывает.
 */
const DMS_PAREN_SRC = `${DEG_NUM}\\s*\\(\\s*${MIN_NUM}\\s*\\(\\s*${SEC_NUM}\\s*\\(\\(`;
const DMS_CORE_SRC = `(?:${DMS_STD_SRC}|${DMS_PAREN_SRC})`;

// Компонент координаты: DMS (град°мин'сек") либо десятичные градусы
const DMS_SRC = `${DMS_CORE_SRC}\\s*${HEMI_SUF_SRC}`;
const DEC_SRC = `[+-]?\\d{1,3}[.,]\\d{3,}\\s*${DEG_SIGN}?\\s*${HEMI_SUF_SRC}`;
const COMP_SRC = `(?:${DMS_SRC}|${DEC_SRC})`;
/**
 * Одиночная компонента с ОБЯЗАТЕЛЬНЫМ полушарием — самостоятельная координата.
 *
 * Пара — не единственная форма записи. В таблицах полигонов широта и долгота стоят в
 * разных ячейках, между ними другие столбцы, и правило пары их не связывает; вторую
 * половину нередко уже забрала соседняя пара. Замер 04.08 на корпусе ЕИС: «45° 44' 38"
 * з.д.» и «20°08'45" с.ш.» оставались открытыми, хотя каждая из них — точная линия на
 * карте и по смыслу ровно та же привязка, что и пара.
 *
 * Точность держат ДВА признака вместе: знак градуса И полушарие. Голое «45°» — это угол
 * наклона или поворота, голое «в.д.» — сокращение «высокого давления» в трубопроводных
 * спецификациях; поодиночке ни то ни другое координатой не является.
 */
const HEMI_SUF_REQ_SRC = `(?:${HEMI_RU_SRC}|[${HEMI}](?![А-Яа-яЁёA-Za-z]))`;
const SOLO_RE = new RegExp(`${DMS_CORE_SRC}\\s*${HEMI_SUF_REQ_SRC}`, "gu");

/**
 * ДИАПАЗОН: «50°00' – 50°40' с. ш.», «132°00' – 133°00' в. д.».
 *
 * Границы участка описывают интервалом, и полушарие ставят ОДИН раз — в конце. Правая
 * половина самодостаточна (её берёт SOLO_RE), а левая остаётся голой и терялась. Замер
 * 05.08 на архиве недропользователя: из 18 пропусков 5 — ровно эта форма
 * («ограниченная координатами 50°00' – 50°40' с. ш. и 132°00' – 133°00' в. д.»).
 *
 * Полушарие правой половины распространяем на левую: в интервале обе границы лежат по
 * одной оси, иначе это не интервал. Тире принимаем в трёх начертаниях плюс дефис.
 */
const RANGE_RE = new RegExp(
  `(${DMS_CORE_SRC})\\s*[–—−-]\\s*(?:${DMS_CORE_SRC})\\s*(${HEMI_SUF_REQ_SRC})`,
  "gu",
);
/**
 * Разделитель пары. Обычный случай — пробел (с необязательной запятой перед ним).
 * Отдельная ветка: запятая БЕЗ пробела, когда десятичный разделитель — точка
 * («в ГСК-11: 48.37197256,135.0878385»). Требование «точка внутри обеих компонент»
 * обязательно: иначе «0,5852 1,1704» распалось бы на четыре числа и пара собралась
 * из чужих половин.
 */
const DEC_DOT_SRC = `[+-]?\\d{1,3}\\.\\d{3,}`;
const PAIR_RE = new RegExp(
  `(?:${COMP_SRC}\\s*[,;]?\\s+${COMP_SRC}|${DEC_DOT_SRC}\\s*,\\s*${DEC_DOT_SRC})`,
  "gu",
);
const COMP_RE = new RegExp(COMP_SRC, "gu");

// ── Якорь для ГОЛОЙ десятичной пары ─────────────────────────────────────────
// Пара вида «0,123 4,567» без градуса и без полушария неотличима от двух соседних
// чисел в таблице анализов — а таких в геологическом отчёте тысячи. Замер на реальных
// отчётах: 635 из 673 находок COORD (94%) были именно такими табличными числами.
// Поэтому голая пара принимается только если (а) у обеих компонент ≥4 знаков после
// запятой (точность градуса ~10 м — так пишут координаты, а не содержания), либо
// (б) рядом стоит слово-маркер. Это тот же приём, что уже применён к СК-42 ниже.
const COORD_MARKER_RE =
  /(?<![A-Za-zА-Яа-яЁё0-9])(?:координат[а-яё]*|широт[а-яё]*|долгот[а-яё]*|WGS[-\s]?84|latitude|longitude)(?![A-Za-zА-Яа-яЁё0-9])/iu;
/**
 * Окно поиска слова-маркера. НАЗАД шире, чем вперёд: маркер — это почти всегда шапка
 * колонки или вводная фраза («Каталог координат угловых точек»), а под ней идут строки
 * таблицы, и к десятой строке заголовок уже дальше сотни знаков.
 */
const COORD_MARKER_BACK = 400;
const COORD_MARKER_FWD = 100;
const DEC_COMP_RE = /[+-]?\d{1,3}[.,]\d+/gu;
const BARE_DEC_MIN_FRACTION = 4;

/** Те же две формы DMS, что и в поиске, но с захватом разрядов — для parseComponent. */
const DMS_STD_PARSE_RE = new RegExp(
  `(${DEG_NUM})${DEG_SEP_SRC}(${MIN_NUM})\\s*${MIN_SIGN}\\s*(?:(${SEC_NUM})\\s*${SEC_SIGN})?`,
  "u",
);
const DMS_PAREN_PARSE_RE = new RegExp(
  `(${DEG_NUM})\\s*\\(\\s*(${MIN_NUM})\\s*\\(\\s*(${SEC_NUM})\\s*\\(\\(`,
  "u",
);

/** Парсит одну компоненту → { value, axis } (axis: 'lat'|'lon'|null по полушарию). */
function parseComponent(s: string): { value: number; axis: "lat" | "lon" | null } | null {
  const hemiMatch = s.match(HEMI_TAIL_RE);
  // У сокращения «с.ш.»/«в.д.» смысл несёт первая буква — она же и в однобуквенной форме.
  const hemi = hemiMatch ? hemiMatch[0].trim()[0]! : null;
  const axis: "lat" | "lon" | null = hemi ? (H_LAT.includes(hemi) ? "lat" : "lon") : null;
  const sign = hemi && H_NEG.includes(hemi) ? -1 : 1;

  // Шаблоны разбора собраны из ТЕХ ЖЕ кусков (DEG_NUM/MIN_NUM/SEC_NUM/знаки), что и шаблоны
  // поиска выше — иначе дубль разъезжается, и найденная строка молча не разбирается.
  const dms = s.match(DMS_STD_PARSE_RE) ?? s.match(DMS_PAREN_PARSE_RE);
  let magnitude: number;
  if (dms) {
    const deg = parseInt(dms[1]!, 10);
    const min = parseFloat(dms[2]!.replace(",", "."));
    const sec = dms[3] ? parseFloat(dms[3].replace(",", ".")) : 0;
    magnitude = deg + min / 60 + sec / 3600;
  } else {
    const num = s.match(/[+-]?\d{1,3}[.,]\d+/u);
    if (!num) return null;
    magnitude = parseFloat(num[0].replace(",", "."));
  }
  // Явный знак минуса в десятичной записи уже в magnitude; полушарие мог его продублировать
  return { value: sign * Math.abs(magnitude), axis };
}

/**
 * Годится ли пара без градуса и полушария (см. COORD_MARKER_RE выше).
 * Пары с ° или полушарием самодостаточны — их не трогаем.
 *
 * ПОЧЕМУ ОДНОГО ПОРОГА ЗНАКОВ НЕ ХВАТИЛО. Правка 01.08 принимала голую пару, если у
 * обеих компонент ≥4 знаков после запятой: у координат точность высокая, у содержаний
 * в таблицах анализов — нет. На отчётах EC это убрало все 635 ложняков. На сметах и
 * ведомостях ЕИС (замер 04.08) правило рассыпалось: объёмы работ пишут как
 * «0,4641946686 0,481416291», десять знаков спокойно проходят порог, и точность COORD
 * упала до 42%. Вывод: «сколько знаков» — свойство ЖАНРА, а не координаты, и как
 * единственный признак не работает нигде, кроме корпуса, на котором подбиралось.
 *
 * Поэтому к голой паре теперь три требования правдоподобия, все дешёвые и жанро-независимые:
 *   • компоненты РАЗНЫЕ — «0,3333 0,3333», «61,6000 61,6000» это повтор ячейки таблицы,
 *     а не точка на карте (совпадение широты с долготой до знака — исчезающе редкий случай);
 *   • обе по модулю ≥ 1 — широты «0,0001°» в документах не встречаются, а доли единицы
 *     в сметах повсюду;
 *   • порог знаков сохраняется как дополнительное условие, но уже не единственное.
 * Слово-маркер рядом («координаты», «широта», WGS-84) по-прежнему перевешивает всё:
 * если автор прямо назвал числа координатами, спорить не с чем.
 */
/** «12.2021» — месяц и год, а не градусы: целая часть 1–12, дробная ровно 4 цифры-год. */
function looksLikeMonthYear(num: string): boolean {
  const [head, tail] = num.replace(",", ".").replace(/^[+-]/, "").split(".");
  if (!head || !tail || tail.length !== 4) return false;
  const month = parseInt(head, 10);
  const year = parseInt(tail, 10);
  return month >= 1 && month <= 12 && year >= 1900 && year <= 2100;
}

/**
 * Минимальная проверка правдоподобия десятичной пары: обе компоненты по модулю ≥ 1.
 *
 * Намеренно НЕ вызывает bareDecimalPairLooksReal: тот набор признаков подбирался под пару
 * вообще без доказательств и требует, среди прочего, четырёх знаков дроби. Здесь автор уже
 * назвал полушарие — это настоящее свидетельство, и «55.409 E 54.819» ронять из-за трёх
 * знаков было бы перебором. Отсекается ровно то, что отсекается: доли градуса.
 */
function decimalMagnitudesPlausible(raw: string): boolean {
  const nums = [...raw.matchAll(DEC_COMP_RE)].map((m) => m[0]);
  if (nums.length < 2) return false;
  return nums.every((n) => Math.abs(parseFloat(n.replace(",", "."))) >= 1);
}

function isAnchoredDecimalPair(text: string, raw: string, index: number): boolean {
  // Знак градуса/минуты/секунды и русское сокращение «с.ш.»/«в.д.» — доказательства
  // самодостаточные: ни то ни другое в числовой таблице не появляется случайно.
  if (ANGLE_SIGN_RE.test(raw) || HEMI_RU_RE.test(raw)) return true;
  // ОДИНОЧНАЯ буква полушария — доказательство слабее, и на неё нужна проверка правдоподобия.
  //
  // Замер 05.08 на архиве недропользователя оставил открытыми ~5 ложных находок вида
  // «0.0413944 0.010645 в»: буква «в» из обычного русского текста стояла отдельным словом
  // сразу за двумя числами из таблицы содержаний — и коротким замыканием отпускала пару
  // мимо ВСЕХ проверок, включая «обе компоненты ≥ 1». Широты в четыре сотых градуса
  // (4 км от экватора) в документах недропользователя не бывает, а доли единицы в таблицах
  // анализов — на каждой странице.
  if (HEMI_ANYWHERE_RE.test(raw)) return decimalMagnitudesPlausible(raw);

  const from = Math.max(0, index - COORD_MARKER_BACK);
  const to = Math.min(text.length, index + raw.length + COORD_MARKER_FWD);
  if (COORD_MARKER_RE.test(text.slice(from, to))) return true;

  // ── Разделитель пары как признак: кто её поставил — человек или колонка таблицы ──
  //
  // Запятую и точку с запятой между половинами пары ставит АВТОР: «55.7558, 37.6173»,
  // «45,050095; 38,981429». Колонки числовой таблицы разделены пробелом или табуляцией —
  // запятой между ячейками не бывает. Это единственный признак разделения, который не
  // зависит от жанра, в отличие от порога знаков после запятой (он проваливался трижды).
  //
  // Запятая-разделитель засчитывается только когда дробная часть отделена ТОЧКОЙ: иначе
  // «0,5852, 1,1704» неразличимо — та же запятая и в роли дроби, и в роли разделителя.
  //
  // ВАЖНО: эти признаки НЕ отменяют проверок правдоподобия ниже, в отличие от маркера.
  // Первая редакция правки 05.08 отпускала пару сразу по знаку — и таблица «0.0027 −0.0000»
  // проехала мимо проверки «обе компоненты ≥1», дав 825 новых ложных находок вместо 924
  // прежних. Признак разделения говорит «пару поставил человек», но НЕ говорит, что это
  // координата.
  const separatedByAuthor =
    /^\s*[+-]?\d{1,3}\.\d+\s*[,;]\s*[+-]?\d{1,3}\.\d+\s*$/u.test(raw)
    || /^\s*[+-]?\d{1,3}[.,]\d+\s*;\s*[+-]?\d{1,3}[.,]\d+\s*$/u.test(raw);
  // Явный знак у компоненты — южная широта или западная долгота.
  const signedComponent = /[+-]\d/u.test(raw);
  if (separatedByAuthor || signedComponent) return bareDecimalPairLooksReal(raw);

  // ── Без маркера голая десятичная пара координатой НЕ считается ──────────────────
  //
  // Раньше здесь был запасной путь: пару принимали без всякого маркера, если она проходила
  // набор признаков правдоподобия (≥4 знаков дроби, компоненты разные, обе ≥1, дробь не
  // добита нулями, не кратны друг другу). Признаки подбирались на отчётах EC и на ЕИС и там
  // работали.
  //
  // Замер 05.08 на архиве недропользователя (D:\filtered_documents, 473 документа) показал,
  // что путь себя не оправдал: 1100 находок COORD, из них 924 — ОДНА И ТА ЖЕ числовая
  // таблица, размноженная по 28 документам («60.2878 75.3598 | 45.2159 52.7519 | … |
  // 1.0048 1.0344» — это ряд C/n, номограмма). Все признаки правдоподобия она проходит:
  // дробь ровно четырёхзначная, компоненты разные, обе больше единицы, отношение дробное.
  // Настоящих координат среди 1100 — порядка двух десятков.
  //
  // Вывод тот же, что и с порогом знаков: набор числовых признаков — свойство корпуса, на
  // котором его подбирали. Единственный признак, который держится в любом жанре, — автор
  // САМ назвал числа координатами. Нет ни знака градуса, ни полушария, ни слова-маркера в
  // окне — доказательств нет, и мы не берём.
  //
  // Цена: пара «13,507939 -44,916183» посреди текста без единого пояснения больше не
  // находится. На корпусах это стоило 4 находок (см. замер в тестах), а сняло 1100 ложных.
  return false;
}

/**
 * Признаки правдоподобия голой пары. Оставлены для маркерного пути (см. выше) и как
 * документация того, что уже было проверено на трёх корпусах: сами по себе они жанро-зависимы.
 */
function bareDecimalPairLooksReal(raw: string): boolean {
  const nums = [...raw.matchAll(DEC_COMP_RE)].map((m) => m[0]);
  if (nums.length < 2) return false;
  // Дата вида «12.2021» тоже число с четырьмя знаками «после запятой»: в сметах рядом
  // стоят индекс-дефлятор и месяц-год («1,1283 12.2021»), и пара выглядела координатой.
  if (nums.some(looksLikeMonthYear)) return false;
  const values = nums.map((n) => Math.abs(parseFloat(n.replace(",", "."))));
  if (values.some((v) => v < 1)) return false;
  // ── Два признака сметной строки. Оба проверены на трёх корпусах и не стоили НИ ОДНОЙ
  // настоящей координаты: на геологии 95→95, на судебных решениях 86→86, а на
  // «сопутствующих» документах ЕИС (акты, ведомости) ложных находок стало 789→37.
  //
  // 1. ДРОБЬ ДОБИТА НУЛЯМИ. «8,50000», «4,00000», «97,75000» — так выглядит колонка
  //    электронной таблицы с фиксированным числом знаков, а не измерение. У координаты,
  //    снятой прибором, последние цифры значащие.
  //
  //    Требуем ПЯТИ знаков: «61,2500» — это Сургут, координата с круглой дробью, и её
  //    ронять нельзя (на этом ловится тест «голая правдоподобная пара с 4+ знаками»).
  //    А вот дробь из пяти и более знаков, кончающаяся нулями, — это ширина колонки,
  //    а не точность прибора.
  if (nums.some((n) => /\d{3}00$/u.test(n.split(/[.,]/)[1] ?? ""))) return false;
  // 2. ВТОРОЕ ЧИСЛО КРАТНО ПЕРВОМУ. «2,00050 30,00750» — это 2,0005 × 15, расценка
  //    и итог; «1,84352 55,30560» — то же самое × 30. Широта и долгота — независимые
  //    измерения, и целая кратность между ними не встречается.
  if (values.length === 2 && values[0]! > 0) {
    const ratio = values[1]! / values[0]!;
    if (Math.round(ratio) >= 2 && Math.abs(ratio - Math.round(ratio)) < 1e-6) return false;
  }
  if (nums[0]!.replace(",", ".") === nums[1]!.replace(",", ".")) return false;
  const fractions = nums.map((n) => n.split(/[.,]/)[1]?.length ?? 0);
  // Пара координат записывается ОДНОЙ точностью: «13,507939 −44,916183», «48.37197256,
  // 135.0878385». Разнобой в знаках выдаёт две разные величины, случайно оказавшиеся рядом:
  // «1,432447895 51,9560» из сметы — это индекс-дефлятор и итог, а не точка на карте.
  if (Math.abs(fractions[0]! - fractions[1]!) > 1) return false;
  return fractions.every((f) => f >= BARE_DEC_MIN_FRACTION);
}

/** Детектит WGS84-пары. Отбрасывает вне диапазона (lat±90, lon±180). */
function detectWGS84(text: string): DetectedCoord[] {
  const out: DetectedCoord[] = [];
  for (const m of text.matchAll(PAIR_RE)) {
    // Триммим краевые пробелы: \s* в компоненте мог захватить хвостовой пробел
    // (иначе одинаковые координаты дают разный raw → ломается дедуп).
    const lead = m[0].length - m[0].trimStart().length;
    const raw = m[0].trim();
    const index = m.index! + lead;
    if (!isAnchoredDecimalPair(text, raw, index)) continue;
    const comps = [...raw.matchAll(COMP_RE)].map((c) => parseComponent(c[0])).filter(Boolean) as {
      value: number;
      axis: "lat" | "lon" | null;
    }[];
    if (comps.length !== 2) continue;

    let latPart = comps.find((c) => c.axis === "lat");
    let lonPart = comps.find((c) => c.axis === "lon");
    // Нет явных полушарий → порядок по умолчанию: широта, потом долгота
    if (!latPart && !lonPart) {
      latPart = comps[0];
      lonPart = comps[1];
    } else if (latPart && !lonPart) {
      lonPart = comps.find((c) => c !== latPart);
    } else if (lonPart && !latPart) {
      latPart = comps.find((c) => c !== lonPart);
    }
    if (!latPart || !lonPart) continue;

    const lat = latPart.value;
    const lon = lonPart.value;
    if (Math.abs(lat) > 90 || Math.abs(lon) > 180) continue; // не географическая пара

    out.push({ raw, index, system: "WGS84", lat, lon });
  }
  return out;
}

// ─── SK-42 (метровая проекционная СК): подпись X=/Y= либо маркер рядом ───────
//
// Х/У — не опечатка: кириллические Х (U+0425) и У (U+0423) визуально
// неотличимы от латинских X/Y и в РФ-документах встречаются вперемешку
// (та же путаница раскладки клавиатуры, что и везде в кириллических
// текстах) — поэтому оба алфавита сразу в классе символов, отдельная
// ветка на кириллицу не нужна.

const SK42_NUM_SRC = "(?<!\\d)\\d{6,8}(?:[.,]\\d+)?(?!\\d)"; // 6–8 цифр целой части (X/Y ± зона)
const SK42_NUM_RE = /\d{6,8}(?:[.,]\d+)?/gu; // тот же паттерн — для извлечения значений из raw

const X_LABEL = "[XxХх]";
const Y_LABEL = "[YyУу]";

// Подписанная пара X=.../Y=... — самодостаточный якорь, маркер СК рядом не
// нужен: такой подписи не бывает у цены/номера договора/ИНН.
//
// Разделитель между меткой и числом — знак «=»/«:» ЛИБО просто пробел. Пробельная форма
// добавлена по замеру 05.08 на отложенном корпусе буровых журналов клиента: там координаты
// пишут «Координаты: X 5843467.386 Y 504372.794» — двоеточие стоит после слова «Координаты»,
// а после самих меток X и Y его нет. Таких пар в корпусе 82 в 9 документах, и правило с
// обязательным «[=:]» не находило НИ ОДНОЙ.
//
// Склейку «X5843467» намеренно НЕ принимаем: пробел обязателен, если знака нет (`\\s+` во
// второй ветке). Иначе в маркшейдерских таблицах любая ячейка вида «Х123456» стала бы
// половиной координаты.
const SK42_LABEL_SEP = `(?:\\s*[=:]\\s*|\\s+)`;
const SK42_LABELED_PAIR_RE = new RegExp(
  `(?<![A-Za-zА-Яа-яЁё0-9])${X_LABEL}${SK42_LABEL_SEP}${SK42_NUM_SRC}\\s*[,;]?\\s+${Y_LABEL}${SK42_LABEL_SEP}${SK42_NUM_SRC}`,
  "gu",
);

// Голая пара чисел БЕЗ подписи — годится только рядом с явным маркером СК
// (см. hasSK42Marker ниже); без него неотличима от двух цен/номеров подряд.
const SK42_BARE_PAIR_RE = new RegExp(`${SK42_NUM_SRC}\\s*[,;]\\s*${SK42_NUM_SRC}`, "gu");

// Маркеры системы координат. МСК требует зонового суффикса «-NN»: голое
// «МСК» в РФ-документах — ЕЩЁ и трёхбуквенный префикс лицензии на
// недропользование (LICENSE_SUBSOIL в deid/detect.ts, формат «МСК 12345
// ТЭ») — без суффикса он от неё неотличим, отсюда обязательный «-NN».
const SK42_MARKER_RE =
  /(?<![A-Za-zА-Яа-яЁё0-9])(?:СК[-\s]?42|SK[-\s]?42|МСК-\d{1,2}|Пулково[-\s]?1942|систем[а-яё]*\s+координат\s+1942\s+года)(?![A-Za-zА-Яа-яЁё0-9])/iu;

const SK42_MARKER_WINDOW = 100; // символов в каждую сторону — «рядом», не «где-то в документе»

/** Маркер СК-42/МСК-NN/Пулково-1942 в окне вокруг найденной голой пары чисел. */
function hasSK42Marker(text: string, start: number, end: number): boolean {
  const from = Math.max(0, start - SK42_MARKER_WINDOW);
  const to = Math.min(text.length, end + SK42_MARKER_WINDOW);
  return SK42_MARKER_RE.test(text.slice(from, to));
}

function buildSK42Entry(match: string, matchIndex: number): DetectedCoord {
  // Тот же приём триммовки краевых пробелов, что и у WGS84 (см. detectWGS84).
  const lead = match.length - match.trimStart().length;
  const raw = match.trim();
  const index = matchIndex + lead;
  const [x, y] = [...raw.matchAll(SK42_NUM_RE)].map((n) => parseFloat(n[0].replace(",", ".")));
  return { raw, index, system: "SK-42", x, y };
}

/** Детектит SK-42-пары: подписанные X=/Y= самодостаточны, голые — только с маркером рядом. */
function detectSK42(text: string): DetectedCoord[] {
  const out: DetectedCoord[] = [];
  for (const m of text.matchAll(SK42_LABELED_PAIR_RE)) {
    out.push(buildSK42Entry(m[0], m.index!));
  }
  for (const m of text.matchAll(SK42_BARE_PAIR_RE)) {
    const start = m.index!;
    const end = start + m[0].length;
    if (!hasSK42Marker(text, start, end)) continue;
    out.push(buildSK42Entry(m[0], start));
  }
  return out;
}

/** Отбрасывает пересекающиеся спаны (оставляет более ранний/длинный) — защита на случай
 *  редкого пересечения между семействами/паттернами; в норме WGS84 и SK-42 не пересекаются
 *  (разная длина целой части) и сами SK-42-паттерны структурно не могут матчить один спан дважды. */
function dropOverlaps(items: DetectedCoord[]): DetectedCoord[] {
  const sorted = [...items].sort((a, b) => a.index - b.index || b.raw.length - a.raw.length);
  const out: DetectedCoord[] = [];
  for (const it of sorted) {
    const end = it.index + it.raw.length;
    if (out.some((k) => it.index < k.index + k.raw.length && k.index < end)) continue;
    out.push(it);
  }
  return out;
}

/** Детектит одиночные компоненты с полушарием (см. SOLO_RE). */
function detectSoloWGS84(text: string): DetectedCoord[] {
  const out: DetectedCoord[] = [];
  for (const m of text.matchAll(SOLO_RE)) {
    const lead = m[0].length - m[0].trimStart().length;
    const raw = m[0].trim();
    const parsed = parseComponent(raw);
    if (!parsed || !parsed.axis) continue;
    if (Math.abs(parsed.value) > (parsed.axis === "lat" ? 90 : 180)) continue;
    out.push({
      raw,
      index: m.index! + lead,
      system: "WGS84",
      ...(parsed.axis === "lat" ? { lat: parsed.value } : { lon: parsed.value }),
    });
  }
  return out;
}

/** Детектит все координаты (WGS84 + SK-42) в тексте. Пары идут первыми: при пересечении
 *  dropOverlaps оставит более длинный спан, то есть пару, а не её половину. */
/**
 * Левая граница диапазона (см. RANGE_RE): полушарие берём у правой границы.
 * Правую не трогаем — её уже забрал detectSoloWGS84, а dropOverlaps снял бы дубль.
 */
function detectRangeWGS84(text: string): DetectedCoord[] {
  const out: DetectedCoord[] = [];
  for (const m of text.matchAll(RANGE_RE)) {
    const left = m[1]!;
    const hemi = m[2]!.trim()[0]!;
    const axis: "lat" | "lon" = H_LAT.includes(hemi) ? "lat" : "lon";
    const parsed = parseComponent(left);
    if (!parsed) continue;
    const value = (H_NEG.includes(hemi) ? -1 : 1) * Math.abs(parsed.value);
    if (Math.abs(value) > (axis === "lat" ? 90 : 180)) continue;
    const lead = left.length - left.trimStart().length;
    out.push({
      raw: left.trim(),
      index: m.index! + lead,
      system: "WGS84",
      ...(axis === "lat" ? { lat: value } : { lon: value }),
    });
  }
  return out;
}

// ─── Координата, РАЗОРВАННАЯ ЯЧЕЙКАМИ ТАБЛИЦЫ ────────────────────────────────
//
// Каталог угловых точек участка — самая частая форма записи координат в извещениях о
// торгах и в отчётах, и почти всегда это ТАБЛИЦА. При извлечении текста таблица
// расплющивается, и координата перестаёт быть непрерывной подстрокой: между широтой и
// долготой встаёт граница ячейки. Правило пары этого не переживает — оно допускает между
// половинами только пробел и запятую.
//
// Замер 06.08 независимой разметкой (137 кусков публичных корпусов, эталон 453 спана):
// на две таких формы приходилось 148 пропусков из 392 — больше трети.

/**
 * ФОРМА 1: обе половины целы, между ними граница ячейки — «|70° 53' |57° 53' |».
 *
 * Границей считаем ТОЛЬКО трубу и табуляцию. Перевод строки сюда не годится: столбец
 * дирекционных углов, вытянутый в колонку, дал бы пару из двух соседних азимутов.
 */
const CELL_BOUNDARY_SRC = `\\s*[|\\t]\\s*`;
const DMS_CELL_PAIR_RE = new RegExp(`(${DMS_SRC})${CELL_BOUNDARY_SRC}(${DMS_SRC})`, "gu");
/**
 * Окно слова-маркера для табличной пары — шире обычного (400 знаков), и не от щедрости.
 * У таблицы шапка одна на все строки: в извещении Роснедра «|Широта(с.ш.) |Долгота(в.д.)»
 * стоит один раз, а последняя строка каталога отстоит от неё на 1134 знака (замер 06.08).
 * С окном 400 правило видело бы только первые четыре точки участка из девяти.
 *
 * Маркер здесь обязателен, в отличие от обычной пары со знаком градуса. Причина ровно та,
 * что зафиксирована тестом «дирекционные углы — НЕ координаты»: азимуты пишут теми же
 * градусами-минутами-секундами и тоже столбцом таблицы, и без шапки «широта/долгота/
 * координаты» отличить каталог точек от ведомости углов нечем.
 */
const CELL_PAIR_MARKER_BACK = 2000;
const CELL_PAIR_MARKER_FWD = 300;

function hasCoordMarkerNear(text: string, start: number, end: number, back: number, fwd: number): boolean {
  return COORD_MARKER_RE.test(text.slice(Math.max(0, start - back), Math.min(text.length, end + fwd)));
}

/**
 * Пара «широта|долгота» через границу ячейки. Спаны отдаём ПОЛОВИНАМИ, а не одним куском:
 * иначе токен съел бы разделитель столбцов и склеил две ячейки таблицы в одну.
 */
function detectCellPairWGS84(text: string): DetectedCoord[] {
  const out: DetectedCoord[] = [];
  for (const m of text.matchAll(DMS_CELL_PAIR_RE)) {
    const left = parseComponent(m[1]!);
    const right = parseComponent(m[2]!);
    if (!left || !right) continue;
    // Ось берём из полушария, если оно есть; иначе порядок «широта, долгота» — тот же
    // умолчательный порядок, что и у обычной пары (detectWGS84).
    const leftIsLat = left.axis ? left.axis === "lat" : right.axis !== "lat";
    const lat = leftIsLat ? left : right;
    const lon = leftIsLat ? right : left;
    if (Math.abs(lat.value) > 90 || Math.abs(lon.value) > 180) continue;
    if (!hasCoordMarkerNear(text, m.index!, m.index! + m[0].length, CELL_PAIR_MARKER_BACK, CELL_PAIR_MARKER_FWD)) {
      continue;
    }
    const leftRaw = m[1]!.trimEnd();
    const rightStart = m.index! + m[0].length - m[2]!.length;
    out.push({ raw: leftRaw, index: m.index!, system: "WGS84", ...(leftIsLat ? { lat: lat.value } : { lon: lon.value }) });
    out.push({
      raw: m[2]!.trimEnd(),
      index: rightStart,
      system: "WGS84",
      ...(leftIsLat ? { lon: lon.value } : { lat: lat.value }),
    });
  }
  return out;
}

/**
 * ФОРМА 2: у координаты каждая ЧАСТЬ в своей ячейке — градусы, минуты и секунды разнесены
 * по столбцам, и в тексте остаётся голый ряд чисел:
 *
 *   «градусы  минуты  секунды  градусы  минуты  секунды
 *      1        56      15      45,12    124      26      33,99 …»
 *
 * Ни знака градуса, ни полушария — от координаты не осталось НИ ОДНОГО признака, кроме
 * шапки таблицы. Поэтому и разбирается это не регуляркой по спану, а маленьким разбором
 * таблицы: находим шапку, читаем идущий за ней ряд чисел, режем его на строки и требуем,
 * чтобы КАЖДАЯ строка читалась как широта-долгота (градусы и минуты целые, минуты и
 * секунды < 60, широта ≤ 90, долгота ≤ 180). Не сошлась хоть одна строка — таблица не
 * координатная, не берём ничего.
 *
 * Двойная шапка (град-мин-сек ДВАЖДЫ) обязательна: одиночное «градусы-минуты-секунды»
 * встречается в требованиях к оформлению («угловые размеры — градусы-минуты-секунды
 * (0°0’0”)»), и там за ним идут слова, а не числа.
 */
const CELL_GAP_SRC = `[^0-9A-Za-zА-Яа-яЁё]{1,25}`;
// «гр.» — такое же сокращение градусов в шапке, как «град.»: замер 06.08 нашёл 16 спанов
// под шапкой «гр. мин. сек. гр. мин. сек.». Сокращение до двух букв безопасно ровно потому,
// что дальше обязаны идти «мин» и «сек» через нецифро-небуквенный зазор: «гр. Иванов» не
// подойдёт.
const DEG_WORD = `(?:град[а-яё]{0,6}|гр)\\.?`;
const MIN_WORD = `мин[а-яё]{0,5}\\.?`;
const SEC_WORD = `сек[а-яё]{0,5}\\.?`;
const COLUMN_HEADERS: { cols: 2 | 3; re: RegExp }[] = [
  {
    cols: 3,
    re: new RegExp(
      `${DEG_WORD}${CELL_GAP_SRC}${MIN_WORD}${CELL_GAP_SRC}${SEC_WORD}${CELL_GAP_SRC}` +
        `${DEG_WORD}${CELL_GAP_SRC}${MIN_WORD}${CELL_GAP_SRC}${SEC_WORD}`,
      "giu",
    ),
  },
  {
    cols: 2,
    re: new RegExp(
      `${DEG_WORD}${CELL_GAP_SRC}${MIN_WORD}${CELL_GAP_SRC}${DEG_WORD}${CELL_GAP_SRC}${MIN_WORD}`,
      "giu",
    ),
  },
];
/** Число в ячейке: целое или с дробной частью. Дробный разделитель внутрь ячейки, не между. */
const CELL_NUM_RE = /\d{1,4}(?:[.,]\d+)?/y;
const CELL_SKIP_RE = /[^0-9A-Za-zА-Яа-яЁё]{1,25}/y;
/** Потолок длины таблицы: 60 точек по 7 чисел с запасом. Защита от разбега по документу. */
const MAX_TABLE_NUMBERS = 500;

interface CellToken {
  text: string;
  start: number;
  end: number;
}

/** Ряд чисел, идущий сразу за шапкой. Останавливается на первой букве. */
function readNumberRun(text: string, from: number): CellToken[] {
  const out: CellToken[] = [];
  let at = from;
  while (out.length < MAX_TABLE_NUMBERS) {
    CELL_SKIP_RE.lastIndex = at;
    const gap = CELL_SKIP_RE.exec(text);
    if (gap) at = gap.index + gap[0].length;
    CELL_NUM_RE.lastIndex = at;
    const num = CELL_NUM_RE.exec(text);
    if (!num) break;
    out.push({ text: num[0], start: at, end: at + num[0].length });
    at += num[0].length;
  }
  return out;
}

const isInt = (s: string): boolean => /^\d+$/u.test(s);
const num = (s: string): number => parseFloat(s.replace(",", "."));

/** Читается ли группа ячеек как угловая величина: целые градусы/минуты, дробь только в конце. */
function angleFromCells(cells: CellToken[], maxDeg: number): number | null {
  for (const [i, c] of cells.entries()) {
    if (i < cells.length - 1 && !isInt(c.text)) return null; // дробь допустима лишь в последнем разряде
  }
  const parts = cells.map((c) => num(c.text));
  if (parts[0]! > maxDeg) return null;
  for (const p of parts.slice(1)) if (p >= 60) return null;
  return parts.reduce((acc, p, i) => acc + p / 60 ** i, 0);
}

function detectColumnTableWGS84(text: string): DetectedCoord[] {
  const out: DetectedCoord[] = [];
  const covered: [number, number][] = [];
  for (const { cols, re } of COLUMN_HEADERS) {
    re.lastIndex = 0;
    for (const h of text.matchAll(re)) {
      const headEnd = h.index! + h[0].length;
      // Шапку «град-мин-сек ×2» трёхколоночное правило уже разобрало — двухколоночному
      // здесь делать нечего, иначе те же числа разметятся дважды и разной нарезкой.
      if (covered.some(([a, b]) => h.index! < b && a < headEnd)) continue;
      const run = readNumberRun(text, headEnd);
      // Ширина строки: с номером точки в первом столбце или без него. Проверяем обе и
      // берём ту, при которой сходится ВСЯ таблица — на одной строке ошибиться легко,
      // на десяти подряд случайное совпадение невероятно.
      for (const width of [cols * 2 + 1, cols * 2]) {
        const indexed = width === cols * 2 + 1;
        if (run.length < width * 2 || run.length % width !== 0) continue;
        const rows: { lat: number; lon: number; cells: CellToken[] }[] = [];
        let prevIndex = -Infinity;
        let ok = true;
        for (let i = 0; i < run.length && ok; i += width) {
          const cells = run.slice(i, i + width);
          if (indexed) {
            const idx = cells[0]!;
            // Номер точки: целый и растущий. Иначе это не столбец нумерации, а данные,
            // и вся нарезка на строки уехала на один столбец.
            if (!isInt(idx.text) || num(idx.text) <= prevIndex) { ok = false; break; }
            prevIndex = num(idx.text);
          }
          const body = indexed ? cells.slice(1) : cells;
          const lat = angleFromCells(body.slice(0, cols), 90);
          const lon = angleFromCells(body.slice(cols), 180);
          if (lat === null || lon === null) { ok = false; break; }
          rows.push({ lat, lon, cells: body });
        }
        if (!ok || !rows.length) continue;
        for (const r of rows) {
          const latCells = r.cells.slice(0, cols);
          const lonCells = r.cells.slice(cols);
          out.push({
            raw: text.slice(latCells[0]!.start, latCells[cols - 1]!.end),
            index: latCells[0]!.start,
            system: "WGS84",
            lat: r.lat,
          });
          out.push({
            raw: text.slice(lonCells[0]!.start, lonCells[cols - 1]!.end),
            index: lonCells[0]!.start,
            system: "WGS84",
            lon: r.lon,
          });
        }
        covered.push([h.index!, run[run.length - 1]!.end]);
        break;
      }
    }
  }
  return out;
}

export function detectCoords(text: string): DetectedCoord[] {
  return dropOverlaps([
    ...detectWGS84(text),
    ...detectSoloWGS84(text),
    ...detectRangeWGS84(text),
    ...detectCellPairWGS84(text),
    ...detectColumnTableWGS84(text),
    ...detectSK42(text),
  ]);
}
