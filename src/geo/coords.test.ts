import { describe, it, expect } from "bun:test";
import { detectCoords } from "./coords";
import { detectEntities } from "../deid/detect";

describe("privacy/geo/coords: детекция", () => {
  it("десятичные градусы, широта-долгота по умолчанию", () => {
    const c = detectCoords("Скважина на 55.7558, 37.6173 пробурена в 2019");
    expect(c).toHaveLength(1);
    expect(c[0]!.lat).toBeCloseTo(55.7558, 4);
    expect(c[0]!.lon).toBeCloseTo(37.6173, 4);
  });

  it("полушария N/E задают ось независимо от порядка", () => {
    const c = detectCoords("точка 37.6173 E, 55.7558 N");
    expect(c).toHaveLength(1);
    expect(c[0]!.lat).toBeCloseTo(55.7558, 4);
    expect(c[0]!.lon).toBeCloseTo(37.6173, 4);
  });

  it("русские полушария С/В и южное → отрицательная широта", () => {
    const c = detectCoords("43.1155 Ю, 131.8855 В");
    expect(c).toHaveLength(1);
    expect(c[0]!.lat).toBeCloseTo(-43.1155, 4);
    expect(c[0]!.lon).toBeCloseTo(131.8855, 4);
  });

  it("формат DMS с секундами", () => {
    const c = detectCoords(`координаты 55°45'21"N 37°37'02"E`);
    expect(c).toHaveLength(1);
    expect(c[0]!.lat).toBeCloseTo(55 + 45 / 60 + 21 / 3600, 4);
    expect(c[0]!.lon).toBeCloseTo(37 + 37 / 60 + 2 / 3600, 4);
  });

  it("вне диапазона (широта > 90) отбрасывается", () => {
    expect(detectCoords("значения 123.4567, 891.2345")).toHaveLength(0);
  });

  it("обычные числа без координатной формы не ловятся", () => {
    // 1-2 знака после запятой не считаем координатой (порог ≥3)
    expect(detectCoords("масса 1.5 кг, глубина 12.7 м")).toHaveLength(0);
  });

  it("несколько пар в тексте", () => {
    const c = detectCoords("от 55.7558, 37.6173 до 59.9343, 30.3351");
    expect(c).toHaveLength(2);
  });

  it("система по умолчанию помечена WGS84", () => {
    const c = detectCoords("55.7558, 37.6173");
    expect(c[0]!.system).toBe("WGS84");
  });
});

describe("privacy/geo/coords: SK-42 (метровая, подпись X=/Y= или маркер СК)", () => {
  it("подписанная пара X = ..., Y = ... (запятая-разделитель)", () => {
    const c = detectCoords("Точка: X = 6165432.10, Y = 4312567.89 на плане участка.");
    expect(c).toHaveLength(1);
    expect(c[0]!.system).toBe("SK-42");
    expect(c[0]!.x).toBeCloseTo(6165432.1, 2);
    expect(c[0]!.y).toBeCloseTo(4312567.89, 2);
    // числовая интерпретация SK-42 — через x/y, НЕ через lat/lon (другая система)
    expect(c[0]!.lat).toBeUndefined();
    expect(c[0]!.lon).toBeUndefined();
  });

  it("подписанная пара X: ... Y: ... (двоеточие, без запятой между компонентами)", () => {
    const c = detectCoords("Координаты устья: X: 6165432.10 Y: 4312567.89.");
    expect(c).toHaveLength(1);
    expect(c[0]!.system).toBe("SK-42");
    expect(c[0]!.x).toBeCloseTo(6165432.1, 2);
    expect(c[0]!.y).toBeCloseTo(4312567.89, 2);
  });

  it("кириллические омоглифы Х=/У= распознаются наравне с латинскими X=/Y=", () => {
    const c = detectCoords("Х = 6234567.01, У = 5178901.23");
    expect(c).toHaveLength(1);
    expect(c[0]!.system).toBe("SK-42");
    expect(c[0]!.x).toBeCloseTo(6234567.01, 2);
    expect(c[0]!.y).toBeCloseTo(5178901.23, 2);
  });

  it("целые метры без дробной части (без знаков после запятой) тоже распознаются", () => {
    const c = detectCoords("X = 6165432, Y = 4312567");
    expect(c).toHaveLength(1);
    expect(c[0]!.x).toBe(6165432);
    expect(c[0]!.y).toBe(4312567);
  });

  it("голая пара чисел рядом с явным маркером «СК-42» детектится", () => {
    const c = detectCoords("Координаты в СК-42: 6165432.10, 4312567.89, погрешность ±0.5 м.");
    expect(c).toHaveLength(1);
    expect(c[0]!.system).toBe("SK-42");
    expect(c[0]!.x).toBeCloseTo(6165432.1, 2);
    expect(c[0]!.y).toBeCloseTo(4312567.89, 2);
  });

  it("голая пара чисел рядом с маркером «МСК-77» (зона региональной СК) детектится", () => {
    const c = detectCoords("Съёмка выполнена в МСК-77, точка 6165432.10, 4312567.89.");
    expect(c).toHaveLength(1);
    expect(c[0]!.system).toBe("SK-42");
  });

  it("несколько SK-42 пар в тексте", () => {
    const c = detectCoords("X = 6165432.10, Y = 4312567.89 и X = 6234567.01, Y = 5178901.23");
    expect(c).toHaveLength(2);
  });

  it("WGS84 и SK-42 в одном тексте детектятся независимо и не мешают друг другу", () => {
    const c = detectCoords(
      "Устье 55.7558, 37.6173 (WGS84); та же точка в СК-42: X = 6165432.10, Y = 4312567.89.",
    );
    expect(c).toHaveLength(2);
    expect(c.map((x) => x.system).sort()).toEqual(["SK-42", "WGS84"]);
  });

  // ── Ложные срабатывания: без якоря (подписи X=/Y= или маркера СК рядом) ──
  // голые 6–8-значные числа НЕ детектятся, даже если разделены запятой.

  it("ложное срабатывание: голая пара БЕЗ маркера СК рядом не ловится", () => {
    expect(detectCoords("Итого: 6165432, 4312567 — сверить перед отправкой.")).toHaveLength(0);
  });

  it("ложное срабатывание: маркер СК-42 ЗА ПРЕДЕЛАМИ окна не считается «рядом»", () => {
    const filler = "слово ".repeat(30); // существенно больше SK42_MARKER_WINDOW
    expect(detectCoords(`СК-42. ${filler}Итого 6165432, 4312567 руб.`)).toHaveLength(0);
  });

  it("ложное срабатывание: цена (два числа подряд) без маркера СК не ловится", () => {
    expect(detectCoords("Стоимость этапов: 6165432, 4312567 рублей суммарно.")).toHaveLength(0);
  });

  it("ложное срабатывание: номер договора не ловится", () => {
    expect(detectCoords("Договор № 6165432 от 01.02.2020 вступает в силу.")).toHaveLength(0);
  });

  it("ложное срабатывание: ИНН (12 цифр подряд) не ловится", () => {
    expect(detectCoords("ИНН 616543211087 у контрагента по сделке.")).toHaveLength(0);
  });

  it("ложное срабатывание: телефон не ловится", () => {
    expect(detectCoords("Телефон +7 916 165-43-21, звонить после 10.")).toHaveLength(0);
  });

  it("ложное срабатывание: префикс лицензии «МСК 12345 ТЭ» (без дефиса-зоны) — не маркер СК", () => {
    // «МСК 12345 ТЭ» — трёхбуквенный региональный префикс лицензии на недропользование
    // (LICENSE_SUBSOIL), а не «местная СК»: у маркера обязателен дефис-зона «МСК-NN».
    expect(
      detectCoords("Лицензия МСК 12345 ТЭ, участок 6234567, 5178901 действует до 2030 года."),
    ).toHaveLength(0);
  });

  // ── Русские сокращения полушарий (замер на реальных отчётах EC, 2026-08-01) ──
  it("градусы с русскими полушариями «с.ш./в.д.» — доминирующая форма в отчётах", () => {
    const c = detectCoords("Участок расположен в точке 56°30'с.ш. 108°45'в.д. по данным съёмки.");
    expect(c).toHaveLength(1);
    expect(c[0]!.raw).toBe("56°30'с.ш. 108°45'в.д.");
    expect(c[0]!.lat).toBeCloseTo(56.5, 3);
    expect(c[0]!.lon).toBeCloseTo(108.75, 3);
  });

  it("русские полушария: южная широта и западная долгота дают минус", () => {
    const c = detectCoords("Точка 12°15'ю.ш. 40°30'з.д. на карте.");
    expect(c).toHaveLength(1);
    expect(c[0]!.lat).toBeCloseTo(-12.25, 3);
    expect(c[0]!.lon).toBeCloseTo(-40.5, 3);
  });

  it("русские полушария: пробелы вокруг точек не мешают", () => {
    const c = detectCoords("Координаты 56 ° 30 ' с. ш. 108 ° 45 ' в. д.");
    expect(c).toHaveLength(1);
  });

  // ── Голая десятичная пара требует якоря (94% ложняков на реальных отчётах) ──
  it("табличные значения с тремя знаками БЕЗ маркера рядом не ловятся", () => {
    // В таблице анализов таких пар тысячи: «0,123 4,567» — это содержания, не координаты.
    expect(detectCoords("Проба А-12 0,123 4,567 8,910 2,345 по результатам анализа.")).toHaveLength(0);
  });

  it("те же три знака ЛОВЯТСЯ, если рядом стоит слово «координаты»", () => {
    const c = detectCoords("Координаты центра: 56,123 108,456 по ведомости.");
    expect(c).toHaveLength(1);
    expect(c[0]!.raw).toBe("56,123 108,456");
  });

  it("четыре знака после запятой самодостаточны — маркер не нужен", () => {
    const c = detectCoords("Значение 56,1234 108,4567 из ведомости.");
    expect(c).toHaveLength(1);
  });

  it("градус самодостаточен: пара с ° ловится и без маркера рядом", () => {
    const c = detectCoords("Отсчёт 56°30' 108°45' снят рулеткой.");
    expect(c).toHaveLength(1);
  });

  it("буква полушария — отдельное слово: «108°45' снят» не съедает «с» от «снят»", () => {
    const c = detectCoords("Отсчёт 56°30' 108°45' снят рулеткой.");
    expect(c).toHaveLength(1);
    expect(c[0]!.raw).toBe("56°30' 108°45'");
  });
});

describe("замер на корпусе ЕИС 04.08: похожие знаки и правдоподобие голых пар", () => {
  it("градус как ordinal indicator «º» и секунды двумя апострофами — ловятся", () => {
    // Реальная запись из отчёта о поисковых работах: «17º59'33'' с. ш., 151º59'50'' в. д.»
    const hits = detectCoords("Участок с координатами: 17º59'33'' с. ш., 151º59'50'' в. д.");
    expect(hits.length).toBe(1);
    expect(Math.round(hits[0]!.lat!)).toBe(18);
    expect(Math.round(hits[0]!.lon!)).toBe(152);
  });

  it("канонический знак градуса продолжает работать", () => {
    expect(detectCoords("56°30' с.ш. 108°45' в.д.").length).toBe(1);
  });

  it("повтор ячейки таблицы «61,6000 61,6000» — не координата", () => {
    expect(detectCoords("Осн. показ. 61,6000 61,6000 аналогам, %").length).toBe(0);
  });

  it("объёмы работ из сметы «0,4641946686 0,481416291» — не координата", () => {
    expect(detectCoords("Расход 0,4641946686 0,481416291 на единицу").length).toBe(0);
  });

  it("доли единицы «0,3333 0,1149885» — не координата (широт 0,3° не бывает)", () => {
    expect(detectCoords("м3 0,3333 0,1149885 35,71").length).toBe(0);
  });

  it("голая пара с маркером рядом принимается несмотря на правдоподобие", () => {
    expect(detectCoords("координаты 55,7558 37,6173").length).toBe(1);
  });

  it("голая правдоподобная пара с 4+ знаками — принимается", () => {
    expect(detectCoords("точка 61,2500 73,4167 на карте").length).toBe(1);
  });
});

